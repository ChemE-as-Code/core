"""``cheme process streams`` (the stream table) and ``cheme process layout``.

:func:`stream_report` is the Python entry point of the stream table: an explicit repository
root in, a :class:`StreamReport` out (streams with units and per-value provenance, balances,
findings, and the source revision of the input files). ``cheme process streams`` is a thin
wrapper that formats it. Neither the function nor this module reads the working directory or
needs the CLI, the server or an agent.
"""

from __future__ import annotations

import csv
import io
import json
import re
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import yaml

from chemeascode.domains.process import FLOWSHEET_FILE, MATERIALS_FILE
from chemeascode.domains.process.model import Balance, Process, balances
from chemeascode.foundation.findings import Finding
from chemeascode.foundation.provenance import SourceRevision, source_revision
from chemeascode.foundation.workspace import (
    LIST_FILES,
    PLANT_FILE,
    NotAPlantRepository,
    Workspace,
)

_SHORT = {"given": "G", "assumed": "A", "calculated": "C"}
COLUMNS = (
    "stream",
    "title",
    "kind",
    "from",
    "to",
    "on BFD",
    "pressure",
    "temperature",
    "flow",
    "composition",
    "phase",
    "duty",
    "calculated",
)


def _mark(provenance: str, is_stale: bool = False) -> str:
    return f"[{_SHORT[provenance]}{' STALE' if is_stale else ''}]"


def _cell(quantity: Any, unit: str, is_stale: bool = False) -> str:
    if quantity is None:
        return ""
    return f"{quantity.value:g} {quantity.unit or unit} {_mark(quantity.provenance, is_stale)}"


def rows(process: Process, case: str) -> list[dict[str, str]]:
    from chemeascode.domains.process.props import stale

    fs = process.flowsheet
    out = []
    for stream in fs.streams:
        state = stream.state.get(case)
        comp = state.composition if state else None
        phase = state.phase if state else None
        old = set(stale(process, stream, case))
        out.append(
            {
                "stream": stream.id,
                "title": stream.title,
                "kind": stream.kind,
                "from": stream.from_,
                "to": stream.to,
                "on BFD": "yes" if process.crossing(stream) else "internal",
                "pressure": _cell(
                    state.pressure if state else None, fs.units.pressure, "pressure" in old
                ),
                "temperature": _cell(
                    state.temperature if state else None, fs.units.temperature, "temperature" in old
                ),
                "flow": _cell(state.flow if state else None, fs.units.flow, "flow" in old),
                "composition": (
                    f"{comp.basis}: "
                    + ", ".join(f"{k} {v:g}" for k, v in comp.values.items())
                    + f" {_mark(comp.provenance, 'composition' in old)}"
                )
                if comp
                else "",
                "phase": (
                    f"{phase.value}"
                    + (f" vf {phase.vapor_fraction:g}" if phase.vapor_fraction is not None else "")
                    + f" {_mark(phase.provenance, 'phase' in old)}"
                )
                if phase
                else "",
                "duty": _cell(state.duty if state else None, fs.units.duty, "duty" in old),
                "calculated": ", ".join(
                    f"{name} {_cell(q, '', name in old)}"
                    for name, q in (state.calculated.items() if state else [])
                ),
            }
        )
    return out


def _balance_lines(process: Process, case: str) -> list[str]:
    lines = []
    for b in balances(process, case):
        if b.status == "no-streams":
            continue
        text = f"{b.kind} {b.node}: {b.status}"
        if b.status in ("ok", "imbalance"):
            text += f" (in {b.inlet:.6g} kg/h, out {b.outlet:.6g} kg/h)"
        if b.extents:
            text += "; extents " + ", ".join(f"{r} {x:.6g} kmol/h" for r, x in b.extents.items())
        if b.failing:
            text += "; " + "; ".join(b.failing)
        if b.missing:
            text += "; missing " + ", ".join(b.missing[:6])
        lines.append(text)
    return lines


def stream_markdown(process: Process, case: str) -> str:
    table = rows(process, case)
    lines = [
        f"Stream table, case {case} (provenance: G given, A assumed, C calculated; STALE: its "
        "inputs changed since it was calculated); generated by "
        "`cheme process streams --md` from process/flowsheet.yaml",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    for row in table:
        lines.append("| " + " | ".join(row[c].replace("|", "/") for c in COLUMNS) + " |")
    lines += ["", "Balances:", ""] + [f"- {line}" for line in _balance_lines(process, case)]
    return "\n".join(lines)


def stream_csv(process: Process, case: str) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(COLUMNS), lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows(process, case))
    return buffer.getvalue()


def _json_payload(
    process: Process, case: str, lists: dict[str, Any], sheet_ids: set[str]
) -> dict[str, Any]:
    from chemeascode.domains.process.props import stale

    fs = process.flowsheet
    streams = []
    for stream in fs.streams:
        state = stream.state.get(case)
        streams.append(
            {
                "id": stream.id,
                "title": stream.title,
                "kind": stream.kind,
                "from": stream.from_,
                "to": stream.to,
                "on_bfd": process.crossing(stream),
                "represented_by": stream.id if process.crossing(stream) else None,
                "template": stream.template,
                "state": state.model_dump(mode="json", exclude_none=True) if state else {},
                "stale": stale(process, stream, case),
                "links": _links(stream, lists, sheet_ids),
            }
        )
    return {
        "case": case,
        "units": fs.units.model_dump(mode="json", exclude_none=True),
        "streams": streams,
        "balances": [b.entry() for b in balances(process, case)],
        "nodes": _nodes(process, lists, sheet_ids),
    }


def _property(quantity: Any, unit: str, is_stale: bool = False) -> dict[str, Any] | None:
    if quantity is None:
        return None
    return {
        "value": quantity.value,
        "unit": quantity.unit or unit,
        "basis": quantity.basis,
        "provenance": quantity.provenance,
        "source": quantity.source,
        "stale": is_stale,
    }


def _links(item: Any, lists: dict[str, Any], sheet_ids: set[str]) -> list[dict[str, Any]]:
    """The links of *item* with their status; the CLI (``--json``) and ``/api/streams`` share
    it, so both report what ``cheme.process-link-unresolved`` reports."""
    from chemeascode.domains.process.model import link_problem

    found = []
    for link in item.links:
        problem = link_problem(link, lists, sheet_ids)
        found.append(
            {**link.model_dump(mode="json"), "resolved": problem is None, "problem": problem}
        )
    return found


def link_context(workspace: Any) -> tuple[dict[str, Any], set[str]]:
    """The parsed equipment, line and instrument lists and the declared sheet ids of
    *workspace*, which links resolve against (an invalid list resolves nothing)."""
    lists = workspace.parsed_lists(("equipment", "lines", "instruments"))
    return lists, {s.id for s in workspace.config().sheets}


# -- the Python entry point ---------------------------------------------------------------------


class UnknownCase(ValueError):
    """The case asked for is not declared in the flowsheet."""


#: The files a stream report is computed from, relative to the root.
REPORT_INPUTS = (
    MATERIALS_FILE,
    FLOWSHEET_FILE,
    PLANT_FILE,
    *(LIST_FILES[k] for k in ("equipment", "lines", "instruments")),
)


@dataclass
class StreamReport:
    """The stream table of one case, with what it was computed from.

    When the process YAML does not load (``loaded`` is False), ``process`` is None or
    ``findings`` hold errors, and the table fields are empty."""

    root: Path
    #: The case reported; None when the process did not load.
    case: str | None
    #: The parsed process files, for further calculations or formatting.
    process: Process | None
    #: Problems found while loading the process YAML (``cheme.process-schema`` and others).
    findings: list[Finding] = field(default_factory=list)
    #: Unit of each quantity kind (``pressure``, ``temperature``, ``flow``, ``duty``, ...).
    units: dict[str, Any] = field(default_factory=dict)
    #: One entry per stream: its ends, the case's state (value, unit, provenance per property),
    #: stale calculated values and resolved links, as ``process streams --json`` prints them.
    streams: list[dict[str, Any]] = field(default_factory=list)
    #: The mass (and component) balance of every block and step, in kg/h.
    balances: list[Balance] = field(default_factory=list)
    #: Feeds, products, blocks and steps with their links.
    nodes: list[dict[str, Any]] = field(default_factory=list)
    #: The git commit and the fingerprints of :data:`REPORT_INPUTS` when this was computed.
    source: SourceRevision = field(default_factory=lambda: SourceRevision(None))

    @property
    def loaded(self) -> bool:
        return self.process is not None and not any(f.level == "error" for f in self.findings)

    def payload(self) -> dict[str, Any]:
        """The document ``cheme process streams --json`` prints."""
        return {
            "case": self.case,
            "units": self.units,
            "streams": self.streams,
            "balances": [b.entry() for b in self.balances],
            "nodes": self.nodes,
        }

    def to_json(self) -> str:
        """``cheme process streams --json``, byte for byte."""
        return json.dumps(self.payload(), indent=2)

    def as_dict(self) -> dict[str, Any]:
        """Everything, JSON-ready: the payload plus findings and the source revision."""
        return {
            **self.payload(),
            # as in validate --json and impact --json
            "findings": [{**asdict(f), "id": f.id} for f in self.findings],
            "source": self.source.as_dict(),
        }


def stream_report(root: Path, case: str | None = None) -> StreamReport:
    """The stream table of *case* (default: the flowsheet's default case) of the plant
    repository at *root*, independent of the working directory.

    Raises :class:`NotAPlantRepository` when *root* holds no ``plant.yaml`` and
    :class:`UnknownCase` when *case* is not declared. A process that does not load is not an
    exception: the report then carries the findings and ``loaded`` is False."""
    from chemeascode.domains.process.model import load

    root = Path(root)
    if not (root / PLANT_FILE).is_file():
        raise NotAPlantRepository(f"No {PLANT_FILE} in {root}.")
    source = source_revision(root, REPORT_INPUTS)
    process, findings = load(root)
    report = StreamReport(root, None, process, findings, source=source)
    if not report.loaded:
        return report
    assert process is not None
    case = case or process.flowsheet.default_case()
    if case not in {c.id for c in process.flowsheet.cases}:
        raise UnknownCase(f"unknown case {case!r}")
    payload = _json_payload(process, case, *link_context(Workspace(root)))
    report.case = case
    report.units = payload["units"]
    report.streams = payload["streams"]
    report.balances = balances(process, case)
    report.nodes = payload["nodes"]
    return report


def _nodes(process: Process, lists: dict[str, Any], sheet_ids: set[str]) -> list[dict[str, Any]]:
    fs = process.flowsheet
    nodes = []
    for kind, items in (
        ("feed", fs.feeds),
        ("product", fs.products),
        ("block", fs.blocks),
        ("step", fs.steps),
    ):
        for item in items:
            nodes.append(
                {
                    "id": item.id,
                    "kind": kind,
                    "title": item.title,
                    "block": getattr(item, "block", None),
                    "links": _links(item, lists, sheet_ids),
                }
            )
    return nodes


def stream_table(
    process: Process, case: str, lists: dict[str, Any], sheet_ids: set[str]
) -> dict[str, Any]:
    """The stream table of *case* for the viewer (``GET /api/streams``): every property with its
    unit, basis, provenance and stale flag, the balances of blocks and steps, the links with
    their status, and the BFD connections with the streams each represents."""
    from chemeascode.domains.process.build import connection_streams
    from chemeascode.domains.process.props import stale

    fs = process.flowsheet
    found = balances(process, case)
    flagged: dict[str, list[str]] = {}
    for b in found:
        if b.status == "imbalance":
            for sid in b.streams_in + b.streams_out:
                flagged.setdefault(sid, []).append(b.node)
    streams = []
    for stream in fs.streams:
        state = stream.state.get(case)
        old = set(stale(process, stream, case))
        comp = state.composition if state else None
        phase = state.phase if state else None
        a, b = process.ends(stream)
        streams.append(
            {
                "id": stream.id,
                "title": stream.title,
                "kind": stream.kind,
                "from": stream.from_,
                "to": stream.to,
                "from_block": process.container(a.node) if a else None,
                "to_block": process.container(b.node) if b else None,
                "on_bfd": process.crossing(stream),
                "template": stream.template,
                "has_state": state is not None,
                "properties": {
                    "pressure": _property(
                        state and state.pressure, fs.units.pressure, "pressure" in old
                    ),
                    "temperature": _property(
                        state and state.temperature, fs.units.temperature, "temperature" in old
                    ),
                    "flow": _property(state and state.flow, fs.units.flow, "flow" in old),
                    "duty": _property(state and state.duty, fs.units.duty, "duty" in old),
                },
                "composition": {**comp.model_dump(mode="json"), "stale": "composition" in old}
                if comp
                else None,
                "phase": {**phase.model_dump(mode="json"), "stale": "phase" in old}
                if phase
                else None,
                "calculated": {
                    name: _property(q, "", name in old)
                    for name, q in (state.calculated.items() if state else [])
                },
                "stale": sorted(old),
                "imbalance": flagged.get(stream.id, []),
                "links": _links(stream, lists, sheet_ids),
            }
        )
    nodes = _nodes(process, lists, sheet_ids)
    titles = {n["id"]: n["title"] for n in nodes}
    return {
        "case": case,
        "cases": [c.model_dump(mode="json") for c in fs.cases],
        "default_case": fs.default_case(),
        "units": fs.units.model_dump(mode="json", exclude_none=True),
        "tolerance": fs.tolerance.model_dump(mode="json"),
        "streams": streams,
        "balances": [
            {**b.entry(), "title": titles.get(b.node, "")}
            for b in found
            if b.status != "no-streams"
        ],
        "nodes": nodes,
        # The connection's id in the BFD sheet and its SVG group is the id of its first stream;
        # with bfd.aggregate one connection represents several parallel streams.
        "bfd_connections": connection_streams(process),
    }


def stream_text(process: Process, case: str) -> str:
    lines = [f"case {case}"]
    for row in rows(process, case):
        values = "; ".join(
            f"{c} {row[c]}"
            for c in ("pressure", "temperature", "flow", "duty", "phase", "calculated")
            if row[c]
        )
        lines.append(f"{row['stream']} {row['from']} -> {row['to']} ({row['on BFD']}): {values}")
    return "\n".join(lines + _balance_lines(process, case))


# -- layout -------------------------------------------------------------------------------------


def _positions(process: Process, view: str) -> dict[str, dict[str, float]]:
    from chemeascode.domains.process.build import place

    placed = place(process, view)
    found = {}
    for node_id, node in placed.nodes.items():
        x, y = node.x, node.y
        home = process.home(node_id)
        if home is not None and home in placed.nodes:
            outer = placed.nodes[home]
            x, y = x - outer.x, y - outer.y
        found[node_id] = {
            "x": round(x, 1),
            "y": round(y, 1),
            "width": round(node.width, 1),
            "height": round(node.height, 1),
        }
    return found


def layout_rows(process: Process, view: str, ids: list[str] | None) -> list[str]:
    pinned = getattr(process.flowsheet.layout, view)
    return [
        f"{view} {node_id}: x {p['x']:g} y {p['y']:g} w {p['width']:g} h {p['height']:g}"
        + (" (pinned)" if node_id in pinned and pinned[node_id].pinned else "")
        + (" (relative to its block)" if process.home(node_id) is not None else "")
        for node_id, p in _positions(process, view).items()
        if not ids or node_id in ids
    ]


def pin_layout(workspace: Any, process: Process, view: str, ids: list[str] | None) -> str:
    """Write the current positions of *view* (all nodes, or *ids*) into ``layout.<view>``."""
    current = process.flowsheet.layout.model_dump(mode="json", exclude_defaults=True)
    target = current.setdefault(view, {})
    count = 0
    for node_id, position in _positions(process, view).items():
        if ids and node_id not in ids:
            continue
        entry = target.setdefault(node_id, {})
        entry.update({k: position[k] for k in ("x", "y")})
        count += 1
    path = workspace.root / FLOWSHEET_FILE
    text = path.read_text(encoding="utf-8")
    block = yaml.safe_dump({"layout": current}, sort_keys=False, default_flow_style=None, width=100)
    found = re.search(r"(?m)^layout:.*\n(?:(?:[ \t]+.*|[ \t]*)\n)*", text)
    if found:
        text = text[: found.start()] + block + text[found.end() :]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")
    return f"{FLOWSHEET_FILE}: pinned {count} object(s) in layout.{view}"

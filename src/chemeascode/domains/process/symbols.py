"""The ISO 10628-2 symbol library: equipment and fitting symbols for the PFD and the P&ID.

``data/iso_shapes.json`` (generated by ``scripts/import_iso_shapes.py``, the selection in
``scripts/iso_shapes.yaml``) holds each symbol in sheet millimetres around (0, 0), Y down, at
scale 1, with its ISO 10628-2 registration number and its connection points. The PFD draws a
step with the symbol of its DEXPI step class (:func:`step_symbol`); the P&ID's shape catalogue
holds them as ``Core/Diagram.Shape`` s (``chemeascode.domains.piping.authoring.shapes``).
"""

from __future__ import annotations

import inspect
import json
from dataclasses import dataclass
from functools import cache
from importlib.resources import files
from typing import Any


@dataclass(frozen=True)
class Port:
    key: str
    x: float
    y: float
    side: str | None
    role: str | None


@dataclass(frozen=True)
class Symbol:
    """One symbol: its catalogue name, what it means, its ISO number and its geometry."""

    name: str
    meaning: str
    #: ISO 10628-2 registration number (``2322``, ``X8079``).
    iso: str
    #: ScaleX/ScaleY to draw it at on an A3 sheet.
    scale: str
    #: A piping component (drawn in the piping colour), not equipment.
    inline: bool
    #: Also in the P&ID template's ShapeCatalogue (the others are added on first use).
    template: bool
    #: DEXPI classes it is the default symbol for.
    classes: tuple[str, ...]
    #: ``{"line": [[x, y], ...]}`` or ``{"ellipse": [x, y], "rx", "ry", "rotation"}``, each with
    #: ``width`` and ``dash``.
    primitives: tuple[dict[str, Any], ...]
    ports: tuple[Port, ...]

    def extent(self) -> tuple[float, float, float, float]:
        """(x0, y0, x1, y1) of the drawing at scale 1."""
        xs: list[float] = []
        ys: list[float] = []
        for p in self.primitives:
            if "line" in p:
                xs += [x for x, _ in p["line"]]
                ys += [y for _, y in p["line"]]
            else:
                cx, cy = p["ellipse"]
                xs += [cx - p["rx"], cx + p["rx"]]
                ys += [cy - p["ry"], cy + p["ry"]]
        return min(xs), min(ys), max(xs), max(ys)


@cache
def symbols() -> dict[str, Symbol]:
    """Symbol name -> symbol, in the order of the selection."""
    raw = json.loads(
        (files("chemeascode.domains.process") / "data/iso_shapes.json").read_text(encoding="utf-8")
    )
    return {
        s["name"]: Symbol(
            name=s["name"],
            meaning=s["meaning"],
            iso=s["iso"],
            scale=s["scale"],
            inline=s["inline"],
            template=s["template"],
            classes=tuple(s["classes"]),
            primitives=tuple(s["primitives"]),
            ports=tuple(Port(**p) for p in s["ports"]),
        )
        for s in raw["shapes"]
    }



"""The report of a HAZOP study: ``build/hazop/<study-id>.md`` and ``.html``.

Derived from ``study.yaml`` only, never edited. It shows the study's state (draft, assessed,
reviewed), its source identity (the analysed inputs at their recorded revisions and whether they
changed since), the matrix and assessment basis, every unresolved item, the worksheet (each
rating with its codes and band, proposals marked as such), the safeguards and the actions with
their status, the review record, and the matrix itself.

Both files are rendered from one list of blocks, so they say the same.
"""

from __future__ import annotations

import html
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from chemeascode.domains.safety.hazop import (
    LoadedStudy,
    RatingRow,
    ReviewStatus,
    scenario_band,
)
from chemeascode.domains.safety.risk_matrix import category_cells
from chemeascode.foundation import provenance
from chemeascode.foundation.findings import Finding

REPORT_DIR = "hazop"

STATE_TEXT = {
    "invalid": "invalid: the study has errors (cheme safety hazop check)",
    "draft": "draft: items are unresolved (listed below)",
    "assessed": "assessed: complete and current, every entry accepted by the team; not yet "
    "covered by a current human review",
    "reviewed": "reviewed: assessed, and a current human review record covers it",
}


@dataclass
class Heading:
    level: int
    text: str


@dataclass
class Para:
    text: str
    strong: bool = False


@dataclass
class Table:
    head: list[str]
    rows: list[list[str]]


@dataclass
class Items:
    items: list[str]


Block = Heading | Para | Table | Items


def _rating_text(row: RatingRow) -> str:
    r = row.rating
    codes = f"{r.category} {r.severity or '?'}/{r.likelihood or '?'}"
    if row.band is None:
        text = f"{codes}: unresolved ({row.message})"
    elif row.state == "current":
        text = f"{codes} → {row.band}"
    elif row.state == "missing":
        text = f"{codes} → {row.band} (not recorded yet)"
    else:
        text = f"{codes} → {row.band} (recorded {row.recorded}: {row.state})"
    if r.status == "proposed":
        text += " [proposed]"
    return text


def _status(status: str, by: str = "") -> str:
    if status == "proposed":
        return "PROPOSED" + (f" by {by}" if by else "")
    return status + (f" ({by})" if by else "")


def report_blocks(
    root: Path,
    loaded: LoadedStudy,
    findings: list[Finding],
    review: ReviewStatus,
    state: str,
    rows: list[RatingRow],
) -> list[Block]:
    """The report of *loaded* as blocks."""
    study = loaded.model
    blocks: list[Block] = []
    if study is None:
        blocks.append(Heading(1, f"HAZOP {loaded.path}"))
        blocks.append(Para("The study does not load; nothing can be reported.", strong=True))
        blocks.append(Items([f.format() for f in findings]))
        return blocks
    matrix = loaded.matrix.model if loaded.matrix is not None else None
    blocks.append(Heading(1, f"HAZOP {study.id}: {study.title}".rstrip(": ")))
    if study.example or (matrix is not None and matrix.example):
        what = "this study" if study.example else "its risk matrix"
        blocks.append(
            Para(
                f"EXAMPLE DATA: {what} is illustrative and not an assessment of a plant.",
                strong=True,
            )
        )
    blocks.append(Para(f"State: {STATE_TEXT.get(state, state)}.", strong=True))
    blocks.append(
        Para(
            "Generated by cheme safety hazop report from "
            f"{loaded.path}; do not edit. The checks are structural: they say whether the study is "
            "consistent, complete and current, not whether the plant is safe. Entries marked "
            "PROPOSED are suggestions the team has not accepted."
        )
    )

    blocks.append(Heading(2, "Study"))
    modes = ", ".join(f"{m.id} ({m.title})" if m.title else m.id for m in study.modes)
    if loaded.matrix is None:
        matrix_text = "none named"
    elif matrix is None:
        matrix_text = f"{loaded.matrix.path} (does not load)"
    else:
        matrix_text = (
            f"{loaded.matrix.path}: {matrix.id} {matrix.title}".rstrip()
            + (" (example data)" if matrix.example else "")
            + f", fingerprint {loaded.matrix.fingerprint}"
            + (f"; source: {matrix.source}" if matrix.source else "")
        )
    team = ", ".join(f"{m.name} ({m.role})" if m.role else m.name for m in study.team)
    if review.record is None:
        review_text = review.detail
    else:
        kind = "human" if review.human else review.reviewer_kind
        currency = "current" if review.current else "not current"
        review_text = (
            f"{review.record}, {kind} review by {review.reviewer}, {currency}: {review.detail}"
        )
    blocks.append(
        Table(
            ["", ""],
            [
                ["Scope", study.scope or "(not stated)"],
                ["Operating modes", modes or "(not stated)"],
                ["Risk matrix", matrix_text],
                ["Assessment basis", study.assessment_basis or "(not stated)"],
                ["Team", team or "(not stated)"],
                ["Review", review_text],
            ],
        )
    )

    blocks.append(Heading(2, "Analysed inputs"))
    if study.analysed:
        table = []
        for basis in study.analysed:
            changed = provenance.changed_since(root, basis.path, basis.revision)
            now = (
                "unchanged"
                if changed == []
                else "cannot be resolved here"
                if changed is None
                else "CHANGED since: reassess"
            )
            table.append([basis.path, basis.relation, basis.revision, now])
        blocks.append(Table(["file", "relation", "revision analysed", "now"], table))
    else:
        blocks.append(Para("None declared: no change can ask for reassessment."))

    blocks.append(Heading(2, "Unresolved and findings"))
    shown = [f for f in findings if f.level in ("error", "warning") or "unresolved" in f.rule]
    shown += [f for f in findings if f not in shown and f.rule.endswith("example")]
    blocks.append(Items([f.format() for f in shown]) if shown else Para("Nothing unresolved."))

    blocks.append(Heading(2, "Worksheet"))
    safeguards = {s.id: s for s in study.safeguards}
    for node in study.nodes:
        blocks.append(Heading(3, f"{node.id} {node.title}".strip()))
        members = ", ".join(m.text() for m in node.members)
        blocks.append(
            Table(
                ["", ""],
                [
                    ["Design intent", node.design_intent or "(not stated)"],
                    ["Members", members or "(none)"],
                    ["Modes", ", ".join(node.modes) or "all"],
                    ["Status", _status(node.status, node.by)],
                ],
            )
        )
        table = []
        for dev in node.deviations:
            deviation = f"{dev.guide_word} {dev.parameter}" + (f" ({dev.id})" if dev.id else "")
            if not dev.scenarios:
                table.append([deviation, "", dev.notes or "(no scenario)", "", "", "", "", "", ""])
            for scen in dev.scenarios:
                mine = [r for r in rows if r.scenario == scen.id]
                which, band = scenario_band(loaded, rows, scen.id)
                initial = "; ".join(_rating_text(r) for r in mine if r.which == "initial")
                residual = "; ".join(_rating_text(r) for r in mine if r.which == "residual")
                guards = "; ".join(
                    f"{g} {safeguards[g].title}"
                    + (" [proposed]" if safeguards[g].status == "proposed" else "")
                    if g in safeguards
                    else f"{g} (unknown)"
                    for g in scen.safeguards
                )
                notes = f" Note: {scen.notes.strip()}" if scen.notes.strip() else ""
                table.append(
                    [
                        deviation,
                        scen.id,
                        scen.cause,
                        scen.consequence + notes,
                        guards or "(none)",
                        initial or "(not rated)",
                        residual or "(not rated)",
                        ", ".join(scen.actions) or "",
                        _status(scen.status, scen.by) + (f"; {which} band {band}" if band else ""),
                    ]
                )
        if table:
            blocks.append(
                Table(
                    [
                        "deviation",
                        "scenario",
                        "cause",
                        "consequence",
                        "safeguards",
                        "initial risk",
                        "residual risk",
                        "actions",
                        "status",
                    ],
                    table,
                )
            )
        else:
            blocks.append(Para("No deviations yet."))

    blocks.append(Heading(2, "Safeguards"))
    blocks.append(
        Table(
            ["id", "safeguard", "kind", "devices", "interlock", "status"],
            [
                [
                    s.id,
                    s.title,
                    s.kind,
                    ", ".join(r.text() for r in s.refs),
                    s.interlock or "",
                    _status(s.status, s.by),
                ]
                for s in study.safeguards
            ],
        )
        if study.safeguards
        else Para("None.")
    )

    blocks.append(Heading(2, "Actions"))
    raised: dict[str, list[str]] = {}
    for _, _, scen in study.scenarios():
        for action in scen.actions:
            raised.setdefault(action, []).append(scen.id)
    blocks.append(
        Table(
            ["id", "action", "scenarios", "owner", "due", "status", "response"],
            [
                [
                    a.id,
                    a.text,
                    ", ".join(raised.get(a.id, [])),
                    a.owner,
                    a.due.isoformat() if a.due else "",
                    a.status.upper() if a.status == "proposed" else a.status,
                    a.response,
                ]
                for a in study.actions
            ],
        )
        if study.actions
        else Para("None.")
    )

    if matrix is not None:
        blocks.append(Heading(2, f"Risk matrix {matrix.id}"))
        blocks.append(
            Para(
                "Bands, lowest risk first: "
                + ", ".join(
                    b.id + (" (requires an action)" if b.requires_action else "")
                    for b in matrix.bands
                )
                + "."
            )
        )
        for cat in matrix.categories:
            cells = category_cells(matrix, cat.id) or {}
            blocks.append(Heading(3, f"{cat.id} {cat.title}".strip()))
            blocks.append(
                Table(
                    ["severity \\ likelihood", *[g.code for g in matrix.likelihood]],
                    [
                        [
                            f"{s.code} {s.descriptions.get(cat.id, s.title)}".strip(),
                            *[(cells.get(s.code) or {}).get(g.code, "") for g in matrix.likelihood],
                        ]
                        for s in reversed(matrix.severity)
                    ],
                )
            )
    return blocks


def _md_cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def to_markdown(blocks: list[Block]) -> str:
    out: list[str] = []
    for block in blocks:
        if isinstance(block, Heading):
            out.append(f"{'#' * block.level} {block.text}")
        elif isinstance(block, Para):
            out.append(f"**{block.text}**" if block.strong else block.text)
        elif isinstance(block, Items):
            out.append("\n".join(f"- {_md_cell(i)}" for i in block.items))
        else:
            head = "| " + " | ".join(_md_cell(h) for h in block.head) + " |"
            rule = "|" + "---|" * len(block.head)
            body = ["| " + " | ".join(_md_cell(c) for c in row) + " |" for row in block.rows]
            out.append("\n".join([head, rule, *body]))
    return "\n\n".join(out) + "\n"


def to_html(blocks: list[Block], title: str) -> str:
    esc = html.escape
    out: list[str] = []
    for block in blocks:
        if isinstance(block, Heading):
            out.append(f"<h{block.level}>{esc(block.text)}</h{block.level}>")
        elif isinstance(block, Para):
            text = esc(block.text)
            out.append(f"<p><strong>{text}</strong></p>" if block.strong else f"<p>{text}</p>")
        elif isinstance(block, Items):
            out.append("<ul>" + "".join(f"<li>{esc(i)}</li>" for i in block.items) + "</ul>")
        else:
            head = "".join(f"<th>{esc(h)}</th>" for h in block.head)
            body = "".join(
                "<tr>"
                + "".join(
                    f"<td class=proposed>{esc(c)}</td>"
                    if "PROPOSED" in c or "[proposed]" in c
                    else f"<td>{esc(c)}</td>"
                    for c in row
                )
                + "</tr>"
                for row in block.rows
            )
            out.append(f"<table><tr>{head}</tr>{body}</table>")
    return (
        "<!doctype html><meta charset=utf-8>"
        f"<title>{esc(title)}</title>"
        "<style>body{font:13px system-ui,sans-serif;margin:16px;max-width:1400px}"
        "table{border-collapse:collapse;margin:8px 0}td,th{border:1px solid #bbb;padding:3px 6px;"
        "text-align:left;vertical-align:top}th{background:#f3f3f3}"
        "td.proposed{background:#fff6d5}</style>" + "".join(out)
    )


def write_report(
    root: Path,
    build: Path,
    loaded: LoadedStudy,
    findings: list[Finding],
    review: ReviewStatus,
    state: str,
    rows: list[RatingRow],
) -> list[Path]:
    """Write ``<build>/hazop/<study-id>.md`` and ``.html``; returns both paths."""
    blocks = report_blocks(root, loaded, findings, review, state, rows)
    name = loaded.model.id if loaded.model is not None else Path(loaded.path).parent.name
    out = build / REPORT_DIR
    out.mkdir(parents=True, exist_ok=True)
    md, page = out / f"{name}.md", out / f"{name}.html"
    md.write_text(to_markdown(blocks), encoding="utf-8")
    page.write_text(to_html(blocks, f"HAZOP {name}"), encoding="utf-8")
    return [md, page]

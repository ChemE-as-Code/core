def template_findings(name: str, block: TitleBlock) -> list[Any]:
    """``cheme.template-metadata``: template defaults still in the title block."""
    from chemeascode.foundation.findings import Finding

    sheet = Path(name).stem
    findings = []

    def warn(what: str, value: str, line: int | None, key: str) -> None:
        findings.append(
            Finding(
                name,
                "warning",
                "cheme.template-metadata",
                f"{what} is {value!r}, a template default (sample data, not this plant's)",
                line=line,
                ids=[key],
                hint=f"set it with `cheme sheet meta {sheet} {key}=...` (empty is fine), "
                "or start sheets with `cheme sheet new`",
            )
        )

    if block.model_name in TEMPLATE_MODEL_NAMES:
        warn("Model name", block.model_name, block.model_line, "ModelName")
    if block.model_uri in TEMPLATE_MODEL_URIS:
        warn("Model uri", block.model_uri, block.model_line, "ModelUri")
    if block.diagram_name in TEMPLATE_DIAGRAM_NAMES:
        warn("Diagram Name", block.diagram_name, block.diagram_line, "DiagramName")
    for prop, (values, line) in block.values.items():
        defaults = TEMPLATE_METADATA.get(prop, frozenset())
        hit = next((v for v in values if v and v in defaults), None)
        if hit is not None:
            warn(f"MetaData {prop}", hit, line, prop)
    return findings


def _status_entries(workspace: Workspace) -> Any:
    path = workspace.root / "checks" / "status.json"
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def stage_signed_off(workspace: Workspace, stage: str) -> bool:
    """Whether ``checks/status.json`` records a sign-off of *stage*.

    Accepts the 0.3 form (``{"checks": [...]}``: every gate of *stage* recorded passes, and
    there is at least one) and a per-stage form (``{"stages": {stage: {...}}}`` or
    ``{stage: {...}}``, whose ``checks``, when given, all pass).
    """
    data = _status_entries(workspace)
    if not isinstance(data, dict):
        return False

    def passed(checks: Any) -> bool:
        return isinstance(checks, list) and all(
            isinstance(c, dict) and c.get("status") in ("pass", "n/a") for c in checks
        )

    stages = data.get("stages") if isinstance(data.get("stages"), dict) else data
    entry = stages.get(stage)
    if isinstance(entry, dict):
        return passed(entry.get("checks", []))
    checks = data.get("checks")
    if isinstance(checks, list):
        mine = [c for c in checks if isinstance(c, dict) and c.get("stage") == stage]
        return bool(mine) and passed(mine)
    return False


def review_records(workspace: Workspace) -> list[Path]:
    """The review records of the repository: ``reviews/**/*.md`` other than README files."""
    folder = workspace.root / "reviews"
    if not folder.is_dir():
        return []
    return sorted(
        p for p in folder.rglob("*.md") if p.name.lower() != "readme.md" and workspace.contains(p)
    )


def _same_sheet_number(number: str, sheet_id: str) -> bool:
    """Whether a SheetNumber names sheet *sheet_id*: the id itself, or its number ("1", "01"
    for P-01)."""
    if number.strip().casefold() == sheet_id.strip().casefold():
        return True
    digits = re.findall(r"\d+", sheet_id)
    return number.strip().isdigit() and bool(digits) and int(number) == int(digits[-1])


def titleblock_findings(
    workspace: Workspace, name: str, block: TitleBlock, sheet: Any | None
) -> list[Any]:
    """``cheme.titleblock-approval`` and ``cheme.titleblock-sheet`` for one sheet."""
    from chemeascode.foundation.findings import Finding

    findings: list[Finding] = []
    stem = sheet.id if sheet is not None else Path(name).stem
    try:
        stage = workspace.config().stage
    except Exception:  # noqa: BLE001 - plant.yaml errors are reported elsewhere
        return findings
    approval = [
        (prop, block.value(prop), block.values[prop][1])
        for prop in ("ApproverName", "ApprovalDateRepresentation")
        if block.value(prop)
    ]
    status = block.value("ApprovalDescription")
    if _APPROVED.match(status):
        approval.append(("ApprovalDescription", status, block.values["ApprovalDescription"][1]))
    if approval and not stage_signed_off(workspace, stage):
        shown = ", ".join(f"{p} {v!r}" for p, v, _ in approval)
        findings.append(
            Finding(
                name,
                "warning",
                "cheme.titleblock-approval",
                f"the title block says approved ({shown}) and checks/status.json has no "
                f"sign-off of stage {stage!r}",
                line=approval[0][2],
                ids=[p for p, _, _ in approval],
                hint=f"empty them (`cheme sheet meta {stem} Approver= ApprovalDate= "
                "Status='for review'`) until the stage is signed off "
                f"(`cheme check --stage {stage} --write`)",
            )
        )
    checker = block.value("CheckerName")
    if checker and not review_records(workspace):
        findings.append(
            Finding(
                name,
                "warning",
                "cheme.titleblock-approval",
                f"the title block names checker {checker!r} and reviews/ holds no review record",
                line=block.values["CheckerName"][1],
                ids=["CheckerName"],
                hint="record the check in reviews/<date>-<topic>.md, or empty CheckerName "
                f"(`cheme sheet meta {stem} Checker=`)",
            )
        )
    if sheet is not None:
        number = block.value("SheetNumber")
        if (
            number
            and not _same_sheet_number(number, sheet.id)
            and number not in TEMPLATE_METADATA["SheetNumber"]
        ):
            findings.append(
                Finding(
                    name,
                    "warning",
                    "cheme.titleblock-sheet",
                    f"SheetNumber is {number!r}; plant.yaml lists this file as sheet {sheet.id}",
                    line=block.values["SheetNumber"][1],
                    ids=["SheetNumber"],
                    hint=f"`cheme sheet meta {sheet.id} SheetNumber={sheet.id}`, or fix plant.yaml",
                )
            )
        drawn = block.value("DrawingName")
        if (
            drawn
            and sheet.title
            and drawn.casefold() not in sheet.title.casefold()
            and sheet.title.casefold() not in drawn.casefold()
            and drawn not in TEMPLATE_METADATA["DrawingName"]
        ):
            findings.append(
                Finding(
                    name,
                    "warning",
                    "cheme.titleblock-sheet",
                    f"DrawingName is {drawn!r}; plant.yaml titles sheet {sheet.id} {sheet.title!r}",
                    line=block.values["DrawingName"][1],
                    ids=["DrawingName"],
                    hint=f"`cheme sheet meta {sheet.id} Title=...`, or fix the title in plant.yaml",
                )
            )
    return findings

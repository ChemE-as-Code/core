"""Sheets and their title blocks: ``cheme sheet new``, ``cheme sheet meta`` and the
title-block rules of ``cheme validate``.

A sheet's title block is its ``PlantMetaData`` (``DrawingNumber``, ``RevisionNumber``,
``ApproverName``, ...) plus the texts of the title-block Label, each a template showing one of
those attributes with its rendering cached in ``<Data property="Text">``. Changing a value means
changing both; :func:`set_metadata` does, rendering each dependent text with pyDEXPI's label
toolkit (the resolution ``cheme.label-stale`` checks against).

The rules:

- ``cheme.template-metadata``: a MetaData value, the ``<Model name/uri>`` or the diagram
  ``Name`` is still a template default (pyDEXPI's sample title block, or the placeholders of the
  template sheet);
- ``cheme.titleblock-approval``: an approver, approval date or status ``approved`` without a
  sign-off of the current stage in ``checks/status.json``, or a checker without a review record;
- ``cheme.titleblock-sheet``: ``SheetNumber`` or ``DrawingName`` disagree with the sheet's
  entry in ``plant.yaml``.
"""


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "plant"


def title_block_values(
    workspace: Workspace,
    sheet_id: str,
    title: str,
    file: str,
    *,
    revision: str | None = None,
    today: datetime.date | None = None,
    total: int | None = None,
) -> dict[str, str]:
    """What ``sheet new`` writes into a new sheet's title block, from ``plant.yaml``.

    *total* is the number of sheets once this one is listed (default: as listed now).
    """
    config = workspace.config()
    project = config.project
    number = project.number if project else ""
    date = (today or datetime.date.today()).isoformat()
    return {
        "ModelName": config.name,
        "ModelUri": f"urn:cheme:{_slug(config.name)}:{sheet_id}",
        "DiagramName": sheet_id,
        "DrawingNumber": f"{number}-{sheet_id}" if number else sheet_id,
        "DrawingName": title,
        "SheetNumber": sheet_id,
        "TotalNumberOfSheets": str(max(len(config.sheets) if total is None else total, 1)),
        "FileName": Path(file).name,
        "ProjectNumber": number,
        "ProjectName": (project.name if project and project.name else config.name),
        "ProcessPlantName": config.name,
        "EnterpriseName": project.client if project else "",
        "SiteName": project.site if project else "",
        "RevisionNumber": revision
        if revision is not None
        else (project.revision if project else "A"),
        "CreationDateRepresentation": date,
        "LastModificationDateRepresentation": date,
        "ApprovalDescription": "for review",
        "ApproverName": "",
        "ApprovalDateRepresentation": "",
        "CheckerName": "",
    }


def _quote(text: str) -> str:
    """*text* as a YAML flow scalar: plain when that reads back as the same string."""
    if (
        re.fullmatch(r"[A-Za-z_][A-Za-z0-9 ._/()+-]*", text)
        and text.strip() == text
        and yaml.safe_load(f"{{k: {text}}}") == {"k": text}
    ):
        return text
    return json.dumps(text, ensure_ascii=False)


@dataclass
class _Registration:
    """How ``plant.yaml`` changes for a new sheet, worked out before anything is written."""

    #: The new ``plant.yaml`` text, or ``None`` when it stays as it is.
    text: str | None
    note: str
    #: How many sheets ``plant.yaml`` lists afterwards.
    total: int


def register_sheet(workspace: Workspace, sheet_id: str, file: str, title: str) -> str:
    """Add the sheet to ``plant.yaml`` (or mark a planned entry drafted). Returns what it did.

    Edits the text, so comments and layout stay. When ``sheets:`` was empty (every
    ``pid/*.xml``), the sheets already in ``pid/`` are listed too, so they stay sheets.
    """
    plan = _plan_registration(workspace, sheet_id, file, title)
    if plan.text is not None:
        (workspace.root / PLANT_FILE).write_text(plan.text, encoding="utf-8", newline="")
    return plan.note


def _plan_registration(workspace: Workspace, sheet_id: str, file: str, title: str) -> _Registration:
    """What :func:`register_sheet` would do; raises :class:`SheetError` before any write."""
    path = workspace.root / PLANT_FILE
    text = path.read_text(encoding="utf-8")
    config = workspace.config()
    entry = next((s for s in config.sheets if s.id == sheet_id), None)
    document = yaml.compose(text)
    sheets_node = next(
        (v for k, v in document.value if isinstance(k, yaml.ScalarNode) and k.value == "sheets"),
        None,
    ) if isinstance(document, yaml.MappingNode) else None  # fmt: skip
    if entry is not None:
        if entry.file != file:
            raise SheetError(f"plant.yaml lists {sheet_id} with file {entry.file}, not {file}")
        if entry.status != "planned":
            return _Registration(None, f"{sheet_id} is already in plant.yaml", len(config.sheets))
        position = config.sheets.index(entry)
        item = sheets_node.value[position]
        status = next(v for k, v in item.value if k.value == "status")
        start, end = status.start_mark.index, status.end_mark.index
        return _Registration(
            text[:start] + "drafted" + text[end:],
            f"plant.yaml: {sheet_id} planned -> drafted",
            len(config.sheets),
        )

    new = [(sheet_id, file, title)]
    if not config.sheets:
        for existing in sorted((workspace.root / "pid").glob("*.xml")):
            relative = workspace.relative(existing)
            if relative != file:
                new.insert(-1, (existing.stem, relative, ""))
    lines = [
        "  - {id: "
        + _quote(i)
        + ", file: "
        + _quote(f)
        + (", title: " + _quote(t) if t else "")
        + "}"
        for i, f, t in new
    ]
    block = "\n".join(lines) + "\n"
    if sheets_node is None:
        text = text.rstrip("\n") + "\nsheets:\n" + block
    elif isinstance(sheets_node, yaml.SequenceNode) and sheets_node.flow_style:
        if sheets_node.value:
            raise SheetError("plant.yaml lists sheets in [...] flow style; add the sheet by hand")
        start, end = sheets_node.start_mark.index, sheets_node.end_mark.index
        text = text[:start].rstrip(" ") + "\n" + block.rstrip("\n") + text[end:]
    elif isinstance(sheets_node, yaml.SequenceNode):
        last = sheets_node.value[-1]
        cut = text.find("\n", last.end_mark.index - 1)
        cut = len(text) if cut < 0 else cut + 1
        indent = " " * sheets_node.value[0].start_mark.column
        block = "\n".join(f"{indent[:-2]}- {line.split('- ', 1)[1]}" for line in lines) + "\n"
        text = text[:cut] + block + text[cut:]
    else:
        raise SheetError("plant.yaml `sheets:` is not a list")
    try:
        PlantConfig.model_validate(yaml.safe_load(text) or {})
    except (ValidationError, yaml.YAMLError) as failure:
        raise SheetError(
            f"adding {sheet_id} would not leave a valid plant.yaml: {failure}"
        ) from failure
    added = ", ".join(i for i, _, _ in new)
    return _Registration(
        text, f"plant.yaml: added {added} to sheets", len(config.sheets) + len(new)
    )


def new_sheet(
    workspace: Workspace,
    sheet_id: str,
    title: str,
    file: str | None = None,
    *,
    revision: str | None = None,
    force: bool = False,
    today: datetime.date | None = None,
) -> tuple[Path, list[str]]:
    """Write a new sheet from the template with its title block filled from ``plant.yaml``."""
    config = workspace.config()
    entry = next((s for s in config.sheets if s.id == sheet_id), None)
    file = file or (entry.file if entry else f"pid/{sheet_id}.xml")
    title = title or (entry.title if entry else "")
    target = workspace.sheet_path(file)
    if target is None:
        raise SheetError(f"{file} is outside the repository")
    if target.exists() and not force:
        raise SheetError(f"{file} exists; pass --force to overwrite it")
    # plant.yaml is checked first, so a refusal leaves no orphan sheet file behind.
    plan = _plan_registration(workspace, sheet_id, file, title)
    values = title_block_values(
        workspace, sheet_id, title, file, revision=revision, today=today, total=plan.total
    )
    content, _ = set_metadata(template_sheet_bytes(), values)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    if plan.text is not None:
        (workspace.root / PLANT_FILE).write_text(plan.text, encoding="utf-8", newline="")
    notes = [f"wrote {file} ({sheet_id}: {title or 'no title'})", plan.note]
    if entry is not None and entry.title and entry.title != title:
        notes.append(
            f"plant.yaml titles {sheet_id} {entry.title!r}: align the two "
            "(cheme.titleblock-sheet warns until they agree)"
        )
    if not config.project:
        notes.append(
            "plant.yaml has no project: block; the title block has no project number, client "
            "or site (see `cheme schema plant`, then `cheme sheet meta`)"
        )
    return target, notes



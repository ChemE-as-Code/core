@dataclass
class TitleBlock:
    """What one sheet's title block says, with the line of each value."""

    model_name: str | None = None
    model_uri: str | None = None
    model_line: int | None = None
    diagram_name: str | None = None
    diagram_line: int | None = None
    #: MetaData property -> (values, line). Multi-language values give one entry per language.
    values: dict[str, tuple[list[str], int | None]] = field(default_factory=dict)

    def value(self, prop: str) -> str:
        """The first (English) value of *prop*, '' when unset."""
        found = self.values.get(prop)
        return found[0][0] if found and found[0] else ""


def _parse(content: bytes) -> etree._Element:
    return etree.fromstring(content, etree.XMLParser(resolve_entities=False, no_network=True))


def _document(root: etree._Element) -> bytes:
    """The whole document of *root*: comments before it (provenance) are its siblings."""
    return etree.tostring(root.getroottree(), xml_declaration=True, encoding="UTF-8")


def _metadata_element(root: etree._Element) -> etree._Element | None:
    return root.find(".//Components[@property='MetaData']/Object")


def _diagram_element(root: etree._Element) -> etree._Element | None:
    return root.find(".//Components[@property='Diagram']/Object[@type='Core/Diagram.Diagram']")


def _data_values(data: etree._Element) -> list[str] | None:
    """The value(s) of one ``<Data>``: a String, Integer, or each language of a multi-language
    string (English first); ``None`` for anything else."""
    scalar = data.find("String")
    if scalar is None:
        scalar = data.find("Integer")
    if scalar is not None:
        return [(scalar.text or "").strip()]
    multi = data.find(f"AggregatedDataValue[@type='{_MULTI}']")
    if multi is None:
        return None
    found = []
    for single in multi.iterfind(f".//AggregatedDataValue[@type='{_SINGLE}']"):
        language = (single.findtext("Data[@property='Language']/String") or "").strip()
        value = (single.findtext("Data[@property='Value']/String") or "").strip()
        found.append((language != "en", value))
    return [value for _, value in sorted(found, key=lambda pair: pair[0])]


def read_title_block(root: etree._Element) -> TitleBlock:
    """The title block of the document *root*."""
    block = TitleBlock(root.get("name"), root.get("uri"), root.sourceline)
    diagram = _diagram_element(root)
    if diagram is not None:
        name = diagram.find("Data[@property='Name']/String")
        if name is not None:
            block.diagram_name = (name.text or "").strip()
            block.diagram_line = name.sourceline
    metadata = _metadata_element(root)
    if metadata is not None:
        for data in metadata.iterchildren("Data"):
            values = _data_values(data)
            if values is not None:
                block.values[data.get("property", "")] = (values, data.sourceline)
    return block


def template_sheet_bytes() -> bytes:
    """The template sheet shipped with cheme-as-code."""
    from importlib.resources import files

    return files("chemeascode.domains.piping").joinpath(*TEMPLATE_SHEET).read_bytes()


@functools.cache
def _template_kinds() -> dict[str, etree._Element]:
    """Each MetaData property of the template sheet, as an empty-valued ``<Data>`` to copy."""
    metadata = _metadata_element(_parse(template_sheet_bytes()))
    assert metadata is not None
    return {d.get("property", ""): d for d in metadata.iterchildren("Data")}


def resolve_key(key: str) -> str:
    """The MetaData property (or ModelName/ModelUri/DiagramName) a ``sheet meta`` key means."""
    folded = key.replace("_", "").replace("-", "").lower()
    if folded in MODEL_KEYS:
        return MODEL_KEYS[folded]
    if folded in ALIASES:
        return ALIASES[folded]
    for prop in _template_kinds():
        if prop.lower() == folded:
            return prop
    known = ", ".join(sorted(_template_kinds()))
    aliases = ", ".join(sorted(ALIASES))
    raise SheetError(
        f"unknown title-block key {key!r}; use a MetaData property ({known}), a short name "
        f"({aliases}) or ModelName, ModelUri, DiagramName"
    )


def _set_data(metadata: etree._Element, prop: str, value: str) -> None:
    template = _template_kinds()
    data = metadata.find(f"Data[@property='{prop}']")
    if data is None:
        data = etree.fromstring(etree.tostring(template[prop]))
        metadata.append(data)
    if data.find("String") is not None:
        data.find("String").text = value
    elif data.find("Integer") is not None:
        if not value.strip().lstrip("-").isdigit():
            raise SheetError(f"{prop} is a whole number, not {value!r}")
        data.find("Integer").text = str(int(value))
    elif data.find(f"AggregatedDataValue[@type='{_MULTI}']") is not None:
        holder = data.find(f"AggregatedDataValue[@type='{_MULTI}']/Data")
        for single in list(holder):
            holder.remove(single)
        single = etree.SubElement(holder, "AggregatedDataValue", type=_SINGLE)
        for name, text in (("Language", "en"), ("Value", value)):
            etree.SubElement(etree.SubElement(single, "Data", property=name), "String").text = text
    else:
        raise SheetError(f"{prop} is not a text value; edit it in the XML")


def _apply(root: etree._Element, values: dict[str, str]) -> None:
    """Set each ``{property: value}`` on the document (MetaData, Model, diagram Name)."""
    metadata = _metadata_element(root)
    if metadata is None:
        raise SheetError("the sheet has no PlantMetaData (Components property='MetaData')")
    for prop, value in values.items():
        if prop == "ModelName":
            root.set("name", value)
        elif prop == "ModelUri":
            root.set("uri", value)
        elif prop == "DiagramName":
            diagram = _diagram_element(root)
            if diagram is None:
                raise SheetError("the sheet has no Diagram")
            name = diagram.find("Data[@property='Name']/String")
            if name is None:
                name = etree.SubElement(
                    etree.SubElement(diagram, "Data", property="Name"), "String"
                )
            name.text = value
        else:
            _set_data(metadata, prop, value)


def refresh_title_block(content: bytes) -> tuple[bytes, list[tuple[str, str, str]]]:
    """Re-render every text showing a MetaData attribute; ``(content, [(id, old, new)])``.

    The result is in canonical form (``cheme fmt``).
    """
    from pydexpi.pydexpi_classes.core.diagram import AttributeRepresentation
    from pydexpi.toolkits.label_toolkit import iter_texts, render_text_template

    from chemeascode.domains.piping import dexpi_io
    from chemeascode.domains.piping.fmt import format_bytes

    content, _ = format_bytes(content)
    model = dexpi_io.load(content, strict=True).model
    metadata = model.conceptualModel.metaData if model.conceptualModel else None
    if metadata is None:
        return content, []
    updates: dict[str, str] = {}
    for text in iter_texts(model.diagram):
        fragments = list(getattr(text.template, "fragments", None) or ())
        shown = [f for f in fragments if isinstance(f, AttributeRepresentation)]
        if not shown or any(f.object is not metadata for f in shown):
            continue
        rendered = render_text_template(text.template)
        if rendered is not None and rendered != (text.text or ""):
            updates[text.id] = rendered
    if not updates:
        return content, []
    root = _parse(content)
    changed = []
    for element in root.iter("Object"):
        new = updates.get(element.get("id", ""))
        if new is None:
            continue
        cached = element.find("Data[@property='Text']/String")
        if cached is None:
            continue
        changed.append((element.get("id"), cached.text or "", new))
        cached.text = new
    content, _ = format_bytes(_document(root))
    return content, changed


def set_metadata(
    content: bytes, values: dict[str, str]
) -> tuple[bytes, list[tuple[str, str, str]]]:
    """*content* with each title-block ``{key: value}`` set and its texts re-rendered."""
    from chemeascode.domains.piping.fmt import FormatRefused

    root = _parse(content)
    _apply(root, {resolve_key(k): v for k, v in values.items()})
    try:
        return refresh_title_block(_document(root))
    except FormatRefused as refusal:
        raise SheetError(f"cannot rewrite the sheet: {refusal}") from refusal



def current_inputs(workspace: Workspace) -> list[str]:
    """The input files a model would record now, except the P&ID sheets (which depend on
    where the placed items are drawn)."""
    found = [LAYOUT_FILES[kind] for kind in LAYOUT_FILES if workspace.layout_file(kind)]
    found += [LIST_FILES[kind] for kind in INPUT_LISTS if workspace.list_file(kind)]
    if workspace.list_file("electrical") is not None:
        found += [LIST_FILES[kind] for kind in CABLING_LISTS if workspace.list_file(kind)]
    return found


def changed_inputs(workspace: Workspace, recorded: dict[str, str]) -> list[str]:
    """The inputs that changed since *recorded* (path -> fingerprint): a recorded file that
    differs or is gone, and an input file that is new."""
    changed = []
    for path, fingerprint in sorted(recorded.items()):
        target = workspace.root / path
        if not target.is_file() or file_fingerprint(target) != fingerprint:
            changed.append(path)
    changed += [path for path in current_inputs(workspace) if path not in recorded]
    return changed


def model_findings(workspace: Workspace) -> list[Finding]:
    """``layout-model-edited``, ``-version``, ``-outdated`` and ``-missing`` (see the module
    text)."""
    name = LAYOUT_MODEL_FILE
    build = "cheme layout build"
    path = workspace.layout_model_file()
    if path is None:
        from chemeascode.foundation.workspace import LAYOUT_SUPPORT

        if any(workspace.layout_file(k) for k in LAYOUT_FILES if k not in LAYOUT_SUPPORT):
            return [
                Finding(
                    name,
                    "info",
                    "cheme.layout-model-missing",
                    f"there are layout files but no generated model {name}",
                    hint=f"run {build} to derive the 3D model (parts, nozzles, envelopes)",
                )
            ]
        return []
    document = read(path.read_text(encoding="utf-8"))
    record = document.get("provenance") if document is not None else None
    if not isinstance(record, dict) or not isinstance(record.get("sources"), dict):
        return [
            Finding(
                name,
                "error",
                "cheme.layout-model-edited",
                f"{name} carries no provenance record of {build}",
                hint=f"never edit the generated model: change its inputs, then {build}",
            )
        ]
    found = []
    if record.get("output_sha256") != output_fingerprint(document):
        found.append(
            Finding(
                name,
                "error",
                "cheme.layout-model-edited",
                f"{name} was edited by hand since it was built (its content no longer matches "
                "the recorded output fingerprint)",
                hint="move the change into layout/*.yaml or the equipment list (dimensions), "
                f"then {build}",
            )
        )
    code = record.get("generator_sha256")
    if record.get("generator_version") != GENERATOR_VERSION or document.get("schema") != SCHEMA:
        found.append(
            Finding(
                name,
                "warning",
                "cheme.layout-model-version",
                f"{name} was built by layout generator {record.get('generator_version')} "
                f"({document.get('schema')}); this cheme-as-code writes {GENERATOR_VERSION} "
                f"({SCHEMA})",
                hint=f"rebuild: {build}",
            )
        )
    elif code != generator_fingerprint():
        found.append(
            Finding(
                name,
                "warning",
                "cheme.layout-model-version",
                f"{name} was built by other layout generator code (code {str(code)[:12]}; "
                f"this cheme-as-code has {generator_fingerprint()[:12]})",
                hint=f"rebuild: {build}",
            )
        )
    else:
        changed = changed_inputs(workspace, record["sources"])
        if changed:
            shown = ", ".join(changed[:6]) + (
                f" and {len(changed) - 6} more" if len(changed) > 6 else ""
            )
            found.append(
                Finding(
                    name,
                    "warning",
                    "cheme.layout-model-outdated",
                    f"{name} is outdated: {shown} changed since it was built",
                    key="sources",
                    hint=f"run {build}",
                )
            )
    return found

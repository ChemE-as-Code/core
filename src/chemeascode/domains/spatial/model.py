"""The generated 3D plant model, ``layout/plant-model.yaml`` (kind ``layout_model``).

:func:`build_model` derives it from the layout files (``layout/site-plan.yaml``,
``building.yaml``, ``equipment-placement.yaml``), the equipment list (``type`` and
``dimensions``), the line list and the P&IDs (nozzles, their DN and connected lines, and the
side of the symbol each is drawn on). ``cheme layout build`` writes it; it is committed
with its inputs and never edited by hand.

Content: the site, areas, roads, racks and buildings as declared, and every placed item with
its parts, nozzles (point, outward direction, DN, references) and maintenance envelopes
(:mod:`chemeascode.domains.spatial.shapes`); ``pipes``, ``structures`` and ``zones`` are empty
for now. Every object has an ``id``, ``refs`` and a ``source`` (``generated``, ``declared`` or
``pinned``). Numbers are rounded to the millimetre and the order is that of the input files, so
a rebuild from the same inputs is byte-identical.

The ``provenance`` block records the generator version, the SHA-256 of the generating modules
(:data:`GENERATOR_MODULES`), a ``sha256:`` fingerprint of each input file and the SHA-256 of
the model's own content (canonical JSON of everything but the provenance).
:func:`model_findings` compares them for ``cheme validate``:

- content changed since it was built: ``cheme.layout-model-edited`` (error);
- generator version, generator code or schema changed: ``cheme.layout-model-version``
  (warning);
- an input changed (or a new input file appeared): ``cheme.layout-model-outdated``
  (warning);
- layout files but no model: ``cheme.layout-model-missing`` (info).
"""


@cache
def generator_fingerprint() -> str:
    """SHA-256 of the :data:`GENERATOR_MODULES` by name and content (line endings
    normalised)."""
    digest = hashlib.sha256()
    here = Path(__file__).parent
    for name in GENERATOR_MODULES:
        path = here / name
        digest.update(name.encode() + b"\0")
        digest.update(path.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return digest.hexdigest()


def output_fingerprint(document: dict[str, Any]) -> str:
    """SHA-256 of the canonical JSON of *document* without its ``provenance``."""
    body = {k: v for k, v in document.items() if k != "provenance"}
    canonical = json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _round(value: Any) -> Any:
    """Floats to the millimetre (3 decimals), -0.0 as 0.0; containers recursively."""
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"not a finite number: {value}")
        return round(value, 3) + 0.0
    if isinstance(value, dict):
        return {k: _round(v) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_round(v) for v in value]
    return value


class _Dumper(yaml.SafeDumper):
    pass


def _scalar(value: Any) -> bool:
    return value is None or isinstance(value, bool | int | float | str)


def _flat(value: Any) -> bool:
    return _scalar(value) or (isinstance(value, list) and all(_scalar(v) for v in value))


def _represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> Any:
    """Numbers and points in flow style (``[x, y, z]``, ``[[x, y], ...]``), the rest in block
    style."""
    flow = all(_scalar(v) for v in data) or all(
        isinstance(v, list) and all(_scalar(x) for x in v) for v in data
    )
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


def _represent_dict(dumper: yaml.SafeDumper, data: dict[str, Any]) -> Any:
    flow = len(data) <= 6 and all(_flat(v) for v in data.values())
    return dumper.represent_mapping("tag:yaml.org,2002:map", data, flow_style=flow)


_Dumper.add_representer(list, _represent_list)
_Dumper.add_representer(dict, _represent_dict)


def dump(document: dict[str, Any]) -> str:
    """The model file's text: :data:`HEADER` and the YAML, in the document's key order."""
    text = yaml.dump(
        document,
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        width=4096,
        default_flow_style=False,
    )
    return HEADER + text


def read(text: str) -> dict[str, Any] | None:
    """The model document of a model file's text; None when it is not a YAML mapping."""
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        return None
    return data if isinstance(data, dict) else None



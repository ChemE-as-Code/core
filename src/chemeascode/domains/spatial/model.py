def _refs(**values: Any) -> dict[str, Any]:
    return {k: (list(v) if isinstance(v, tuple) else v) for k, v in values.items() if v}


def _sheet_files(workspace: Workspace) -> tuple[dict[str, Path], list[Path]]:
    """The P&ID files by sheet id (and by file path), and every P&ID file in order."""
    by_id: dict[str, Path] = {}
    try:
        config = workspace.config()
    except Exception:  # noqa: BLE001 - plant.yaml problems are validate's to report
        return {}, []
    for sheet in config.sheets:
        if sheet.kind != "pid":
            continue
        path = workspace.sheet_path(sheet.file)
        if path is not None:
            by_id[sheet.id] = path
            by_id[sheet.file] = path
    return by_id, workspace.pid_files()


class _Sheets:
    """P&ID sheets, loaded on demand, with the equipment each draws."""

    def __init__(self, workspace: Workspace) -> None:
        from chemeascode.domains.piping import dexpi_io
        from chemeascode.domains.spatial.pid_nozzles import sheet_equipment

        self.workspace = workspace
        self.by_id, self.files = _sheet_files(workspace)
        self.loaded: dict[Path, dict[str, Any]] = {}
        self.networks: dict[Path, list[Any]] = {}
        self.functions: dict[Path, list[Any]] = {}
        self.findings: list[Finding] = []
        self._load = dexpi_io.load
        self._equipment = sheet_equipment

    def equipment(self, path: Path) -> dict[str, Any]:
        if path not in self.loaded:
            name = self.workspace.relative(path)
            found: dict[str, Any] = {}
            if path.is_file():
                try:
                    from chemeascode.domains.spatial.pid_network import sheet_network

                    model = self._load(path.read_bytes(), strict=True).model
                    found = self._equipment(model, name)
                    self.networks[path] = sheet_network(model, name)
                    from chemeascode.domains.control.electrical import instrument_functions

                    self.functions[path] = instrument_functions(model, name)
                except Exception as failure:  # noqa: BLE001 - reported, the build goes on
                    self.findings.append(
                        Finding(
                            name,
                            "warning",
                            "cheme.layout-model-sheet",
                            f"{name} could not be loaded, so its nozzles are left out: "
                            f"{str(failure).splitlines()[0][:160]}",
                            hint="run cheme validate for the reason",
                        )
                    )
            self.loaded[path] = found
        return self.loaded[path]

    def network(self) -> list[Any]:
        """Every piping segment of every P&ID, in sheet order."""
        found = []
        for path in self.files:
            self.equipment(path)
            found += self.networks.get(path, [])
        return found

    def instrument_functions(self) -> list[Any]:
        """Every instrument function of every P&ID, in sheet order."""
        found = []
        for path in self.files:
            self.equipment(path)
            found += self.functions.get(path, [])
        return found

    def find(self, tag: str, sheet: str | None) -> tuple[Any, Path | None]:
        """The P&ID item of *tag*: on its listed *sheet* first, then on every P&ID."""
        first = self.by_id.get(sheet) if sheet else None
        for path in ([first] if first else []) + [p for p in self.files if p != first]:
            item = self.equipment(path).get(tag)
            if item is not None:
                return item, path
        return None, None


def _spread_keys(nozzles: list[Any]) -> dict[str, int]:
    """For nozzles drawn at the same spot of the same side, the how-many-th each is."""
    seen: dict[tuple[str, int], int] = {}
    found = {}
    for nozzle in sorted(nozzles, key=lambda n: (n.offset, n.name)):
        u, v = nozzle.offset
        along = u if nozzle.side in ("top", "bottom") else v
        key = (nozzle.side, round(along / SAME_SPOT))
        found[nozzle.name] = seen.get(key, 0)
        seen[key] = found[nozzle.name] + 1
    return found


def _drawn(nozzle: Any, shape: str, tall: bool) -> tuple[str | None, float, float]:
    """The side and offset to place *nozzle* by; a horizontal item drawn upright has its axis
    along the sheet's y, so the offset is turned onto the item's axis."""
    from chemeascode.domains.spatial.pid_nozzles import side_of

    u, v = nozzle.offset
    if shape == "horizontal_cylinder" and tall:
        u, v = v, u
        return side_of(u, v), u, v
    return nozzle.side, u, v


def _part(tag: str, part: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "id": f"{tag}/{part.id}",
        "refs": {"tag": tag},
        "source": "generated",
        "kind": part.kind,
        "material": part.material,
    }
    for name in (
        "start",
        "end",
        "radius",
        "radius_end",
        "centre",
        "axis",
        "depth",
        "size",
        "rotation_deg",
        "tube",
        "ref",
        "arc_deg",
        "size_end",
        "lod",
    ):
        value = getattr(part, name)
        if value is not None:
            entry[name] = value
    return entry


def _inward(solids: list[Any], point: Any, direction: Any) -> float:
    """How far back from *point* (against *direction*) the first of *solids* is, in 2 cm
    steps up to :data:`NECK_REACH`; 0 when *point* touches one, :data:`NECK_REACH` / 3 when
    none is met."""
    steps = round(NECK_REACH / 0.02)
    for k in range(steps + 1):
        t = 0.02 * k
        p = tuple(point[i] - direction[i] * t for i in range(3))
        if any(solid.distance(p) <= 1e-6 for solid in solids):
            return t
    return NECK_REACH / 3


def _nozzle_detail(
    body: Any, nozzle: Any, anchor: Any, solids: list[Any], connected: bool, base_z: float
) -> tuple[list[Any], Any]:
    """The level-2 parts of a nozzle (neck and flange; a transmitter on its stand at an
    unconnected instrument tapping) and the point where its pipe connects: a machine's real
    flange as it is; on a machine's envelope the flange stays and the neck reaches back to the
    body; else the neck stands out of the shell and the point moves to the flange's face."""
    from chemeascode.domains.piping.pipe_data import outside_diameter
    from chemeascode.domains.spatial.shape_details import fit_flange, nozzle_flange, transmitter

    od = outside_diameter(nozzle.dn if nozzle.dn is not None else TAPPING_DN)
    if anchor.flange:
        if nozzle.dn is not None:
            fit_flange(body, anchor.point, od)
        return [], anchor.point
    machine = body.family in ("pump", "compressor", "turbine") and body.variant != "machine"
    inward = _inward(solids, anchor.point, anchor.direction) if machine else 0.0
    parts, face = nozzle_flange(nozzle.name, anchor.point, anchor.direction, od, inward)
    if not connected and nozzle.dn is None:
        parts += transmitter(nozzle.name, face, anchor.direction, base_z)
    return parts, face


def _piping_detail(document: dict[str, Any], lines: Any, plan: Any = None) -> None:
    """Valve and instrument parts, pipe supports and jacketing (``piping_detail``)."""
    from chemeascode.domains.spatial.piping_detail import inline_parts, jacket, supports

    texts = {line.number: line.insulation for line in getattr(lines, "lines", None) or []}
    for pipe in document["pipes"]:
        found = jacket(pipe.get("insulation_mm", 0.0), texts.get(pipe["line"]))
        if found is not None:
            pipe["jacket"] = found
    inline_parts(document)
    for item in document["inline"]:
        if item.get("parts"):
            item["parts"] = _with_refs(item["parts"], {"lines": item["refs"].get("lines")})
    document["supports"] = supports(document)
    for support in document["supports"]:
        support["parts"] = _with_refs(support["parts"], {"lines": support["refs"]["lines"]})
    from types import SimpleNamespace

    from chemeascode.domains.spatial.criteria import criteria
    from chemeascode.domains.spatial.piping_detail import support_proposals
    from chemeascode.domains.spatial.structures import support_steel

    found = criteria(plan)
    clearance, stub_max = found.support_pipe_clearance_m, found.support_stub_max_m
    for proposal in support_proposals(document, clearance, stub_max):
        shape = SimpleNamespace(**{**proposal, "section": None})
        proposal["parts"] = _with_refs(
            support_steel(shape, proposal["base"]), {"lines": proposal["refs"]["lines"]}
        )
        document["support_steel"].append(proposal)


def _declared_supports(document: dict[str, Any], structures: Any, file: str) -> list[dict]:
    """The declared ``pipe_supports`` of ``layout/structures.yaml`` with their parts, each
    standing on grade or on the steel below (its ``base``, else the highest member under it)."""
    from chemeascode.domains.spatial.piping_detail import steel_below
    from chemeascode.domains.spatial.structures import support_steel

    found = []
    for support in getattr(structures, "pipe_supports", None) or []:
        base = 0.0
        if support.from_ == "steel":
            below = support.base
            if below is None:
                below = steel_below(document, tuple(support.at), support.top)
            base = below if below is not None else 0.0
        data = support.model_dump(mode="json", by_alias=True, exclude={"from_", "section", "notes"})
        data.pop("from", None)
        entry = {
            "id": data.pop("id"),
            "refs": {"file": file},
            "source": "declared",
            **data,
            "base": base,
            "parts": _with_refs(support_steel(support, base), {"file": file}),
        }
        found.append(entry)
    return found


def _area(area: Any, file: str, declared: Any) -> dict[str, Any]:
    """An area's model entry; a bund with its wall height and walls."""
    from chemeascode.domains.spatial.schemas import BUND_WALL_HEIGHT
    from chemeascode.domains.spatial.structures import bund_walls

    if area.kind != "bund":
        return declared(area, file)
    height = area.wall_height if area.wall_height is not None else BUND_WALL_HEIGHT
    entry = declared(area, file, wall_height=height)
    entry["parts"] = _with_refs(bund_walls(area, height), {"file": file})
    return entry


def _with_refs(parts: list[dict[str, Any]], refs: dict[str, Any]) -> list[dict[str, Any]]:
    return [{"id": p["id"], "refs": refs, "source": "generated", **p} for p in parts]


def build_model(
    workspace: Workspace,
    only: set[str] | None = None,
    previous: dict[str, Any] | None = None,
) -> Model:
    """The model of *workspace* as it is now (see the module text). Raises :class:`BuildError`
    without layout files or while one of them is invalid.

    *only*: route just these line numbers; the other pipes are taken from *previous* (the
    committed model) where it has them, else listed as not routed in this run."""
    from chemeascode.domains.spatial.layout_validate import (
        building_footprint,
        building_heights,
        level_heights,
        listed_item,
        resolve,
        workspace_layout,
    )
    from chemeascode.domains.spatial.routing import route_model
    from chemeascode.domains.spatial.schemas import RoutingRules
    from chemeascode.domains.spatial.structures import (
        building_parts,
        frame_structure,
        platforms_for,
        rack_ladders,
        rack_steel,
        step_overs,
    )
    from chemeascode.domains.spatial.zones import line_radii, zone_entries

    lists = workspace.parsed_lists(INPUT_LISTS)
    equipment = lists.get("equipment")
    piping_items = lists.get("piping_items")
    layout = workspace_layout(workspace, equipment, piping_items)
    from chemeascode.foundation.workspace import LAYOUT_SUPPORT

    if not [kind for kind in layout.present if kind not in LAYOUT_SUPPORT]:
        raise BuildError("no layout files (layout/site-plan.yaml, building.yaml, ...)")
    invalid = [
        f
        for f in layout.findings
        if f.rule in ("yaml.syntax", "yaml.schema", "cheme.layout-unreadable")
    ]
    if invalid:
        raise BuildError("a layout file is invalid; fix it first", invalid)

    findings: list[Finding] = []
    stats = {"items": 0, "parts": 0, "pid": 0, "default": 0, "override": 0, "envelopes": 0}
    sheets = _Sheets(workspace)
    used_sheets: set[Path] = set()
    placement_name = LAYOUT_FILES["placement"]
    placement_path = workspace.layout_file("placement")
    document_node = None
    if placement_path is not None:
        try:
            document_node = yaml.compose(placement_path.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            document_node = None

    def add(level: str, rule: str, message: str, loc: tuple[Any, ...], tag: str, hint: str):
        findings.append(
            Finding(
                placement_name,
                level,  # type: ignore[arg-type]
                f"cheme.layout-{rule}",
                message,
                line=_yaml_line(document_node, loc) if document_node is not None else None,
                ids=[tag],
                hint=hint,
            )
        )

    items: list[dict[str, Any]] = []
    seen: set[str] = set()
    placements = layout.placement.equipment if layout.placement else []
    for index, item in enumerate(placements):
        if item.tag in seen:
            continue  # validate reports the duplicate
        seen.add(item.tag)
        listed = listed_item(item.tag, equipment, piping_items)
        pid, pid_path = sheets.find(item.tag, getattr(listed, "sheet", None))
        if pid_path is not None:
            used_sheets.add(pid_path)
        resolved = resolve(item, listed, pid.tube_length if pid is not None else None)
        body = resolved.body
        sheet_name = workspace.relative(pid_path) if pid_path is not None else None
        overrides = {n.id: (k, n) for k, n in enumerate(item.nozzles)}
        nozzles: list[dict[str, Any]] = []
        pid_nozzles = list(pid.nozzles) if pid is not None else []
        known = set(pid.names) if pid is not None else set()
        for name, (k, _) in overrides.items():
            if pid is not None and name not in known:
                add(
                    "error",
                    "nozzle-unknown",
                    f"{item.tag} has no nozzle {name} on its P&ID {sheet_name}",
                    ("equipment", index, "nozzles", k),
                    item.tag,
                    f"nozzles of {item.tag}: {', '.join(sorted(known)) or 'none'}",
                )

        from chemeascode.domains.spatial.geometry3d import part_solid

        envelope = [part_solid(_part(item.tag, p), detail=True) for p in body.parts()]
        solids = [solid for solid in envelope if solid is not None]
        nozzle_parts: list[Any] = []
        chosen = {
            n.dexpi_id: next(
                (overrides[key][1] for key in (n.name, n.dexpi_id) if key in overrides), None
            )
            for n in pid_nozzles
        }
        drawn = [n for n in pid_nozzles if chosen[n.dexpi_id] is None and n.side is not None]
        spread = _spread_keys(drawn)
        defaulted = [n for n in pid_nozzles if chosen[n.dexpi_id] is None and n.side is None]
        for nozzle in pid_nozzles:
            override = chosen[nozzle.dexpi_id]
            side = None
            if override is not None:
                anchor = body.anchor(
                    angle_deg=override.angle_deg,
                    elevation=override.elevation,
                    along=override.along,
                    face=override.face,
                    offset=override.offset or (0.0, 0.0),
                )
                basis, source = "override", "declared"
            elif nozzle.side is not None:
                side, u, v = _drawn(nozzle, body.shape, pid.drawn_tall)
                anchor = body.pid_anchor(side or nozzle.side, u, v, spread[nozzle.name])
                side = nozzle.side
                basis, source = "pid", "generated"
            else:
                anchor = body.default_anchor(defaulted.index(nozzle), len(defaulted))
                basis, source = "default", "generated"
            stats[basis] += 1
            entry: dict[str, Any] = {
                "id": f"{item.tag}/{nozzle.name}",
                "refs": _refs(
                    tag=item.tag,
                    dexpi=nozzle.dexpi_id,
                    sheet=sheet_name,
                    lines=nozzle.lines,
                    segments=nozzle.segments,
                ),
                "source": source,
                "name": nozzle.name,
            }
            if nozzle.dn is not None:
                entry["dn"] = nozzle.dn
            detail, face = _nozzle_detail(
                body,
                nozzle,
                anchor,
                solids,
                bool(nozzle.segments),
                item.position[2],
            )
            nozzle_parts += detail
            entry.update(point=face, direction=anchor.direction, basis=basis)
            if face != anchor.point:
                entry["base"] = anchor.point
            if side is not None:
                entry["side"] = side
            nozzles.append(entry)
        listed_tags = {e.tag for e in equipment.equipment} if equipment is not None else set()
        if pid is None and item.tag in listed_tags:
            add(
                "info",
                "nozzle-defaulted",
                f"{item.tag} is drawn on no P&ID, so it has no nozzles",
                ("equipment", index),
                item.tag,
                "draw it on its sheet (equipment list sheet:) and rebuild",
            )
        elif defaulted:
            add(
                "info",
                "nozzle-defaulted",
                f"{item.tag}: {len(defaulted)} of {len(pid_nozzles)} nozzles are not drawn with "
                f"a position on {sheet_name} and were placed by default "
                f"({', '.join(n.name for n in defaulted)})",
                ("equipment", index),
                item.tag,
                "give them a position in nozzles: of the placement where it matters",
            )
        from chemeascode.domains.spatial.shape_details import manways

        x0, y0 = item.position[0], item.position[1]
        angles = [
            math.degrees(math.atan2(n["base"][1] - y0, n["base"][0] - x0)) - item.rotation_deg
            if "base" in n
            else math.degrees(math.atan2(n["point"][1] - y0, n["point"][0] - x0))
            - item.rotation_deg
            for n in nozzles
        ]
        manways(body, angles)
        parts = [_part(item.tag, part) for part in [*body.parts(), *nozzle_parts]]
        envelopes = [
            {
                "id": f"{item.tag}/{envelope.kind}",
                "refs": {"tag": item.tag},
                "source": "generated",
                "kind": envelope.kind,
                "centre": envelope.centre,
                "size": envelope.size,
                "rotation_deg": envelope.rotation_deg,
            }
            for envelope in body.envelopes()
        ]
        stats["items"] += 1
        stats["parts"] += len(parts)
        stats["envelopes"] += len(envelopes)
        dims = {
            name: getattr(body.dims, name)
            for name in ("diameter", "height", "length", "width", "head", "support")
            if getattr(body.dims, name) is not None
        }
        weight = getattr(getattr(listed, "dimensions", None), "weight", None)
        if weight is not None:
            dims["weight"] = weight
        lift_weight = getattr(getattr(listed, "dimensions", None), "lift_weight", None)
        if lift_weight is not None:
            dims["lift_weight"] = lift_weight
        items.append(
            {
                "id": item.tag,
                "refs": _refs(
                    tag=item.tag,
                    dexpi=pid.dexpi_id if pid is not None else None,
                    sheet=sheet_name,
                    file=placement_name,
                ),
                "source": "declared",
                "tag": item.tag,
                "type": resolved.type,
                "family": body.family,
                "shape": body.shape,
                "size_from": resolved.size_from,
                "dimensions": dims,
                "position": item.position,
                "rotation_deg": item.rotation_deg,
                "mount": item.mount.model_dump(exclude_none=True) if item.mount else None,
                **({"plinth": item.plinth} if item.plinth is not None else {}),
                "bbox": body.bbox(),
                "parts": parts,
                "nozzles": nozzles,
                "envelopes": envelopes,
            }
        )
    findings += sheets.findings

    plan = layout.site_plan
    site_file = LAYOUT_FILES["site_plan"]
    building_file = LAYOUT_FILES["building"]

    def declared(obj: Any, file: str, **extra: Any) -> dict[str, Any]:
        data = obj.model_dump(mode="json")
        return {"id": data.pop("id"), "refs": {"file": file}, "source": "declared", **data, **extra}

    buildings = []
    for building in layout.buildings.buildings if layout.buildings else []:
        clear = {level.id: height for level, height, _ in level_heights(building)}
        entry = declared(
            building,
            building_file,
            footprint=building_footprint(building),
            heights=building_heights(building),
        )
        for level in entry["levels"]:
            level["clear_height"] = clear[level["id"]]
        entry["parts"] = _with_refs(
            building_parts(building, building_heights(building)[1]),
            {"file": building_file},
        )
        buildings.append(entry)
    rules = layout.routing.rules if layout.routing is not None else RoutingRules()
    racks = []
    for rack in plan.racks if plan else []:
        entry = declared(rack, site_file)
        others = [other for other in plan.racks if other.id != rack.id]
        entry["parts"] = _with_refs(
            rack_steel(rack, rules.rack_bent_spacing_m, others),
            {"file": site_file},
        )
        entry["ladders"] = rack_ladders(rack, others, site_file)
        for ladder in entry["ladders"]:
            ladder["parts"] = _with_refs(ladder["parts"], {"file": site_file})
        racks.append(entry)
    structures_file = LAYOUT_FILES["structures"]
    structures = []
    from chemeascode.domains.spatial.criteria import criteria

    remote = criteria(plan).escape_remote_fraction
    dead_end = criteria(plan).dead_end_m
    for structure in layout.structures.structures if layout.structures else []:
        entry = frame_structure(structure, structures_file, remote, dead_end)
        refs = {"file": structures_file}
        entry["parts"] = _with_refs(entry["parts"], refs)
        entry["walls"] = _with_refs(entry["walls"], refs)
        for stair in entry["stairs"]:
            stair["parts"] = _with_refs(stair["parts"], refs)
        for ladder in entry["ladders"]:
            ladder["parts"] = _with_refs(ladder["parts"], refs)
        structures.append(entry)
    document: dict[str, Any] = {
        "schema": SCHEMA,
        "kind": "layout_model",
        "provenance": {},
        "units": "m",
        "site": (
            {
                "id": "site",
                "refs": {"file": site_file},
                "source": "declared",
                **plan.site.model_dump(mode="json"),
            }
            if plan is not None
            else None
        ),
        "areas": [_area(a, site_file, declared) for a in plan.areas] if plan else [],
        "roads": [declared(r, site_file) for r in plan.roads] if plan else [],
        "racks": racks,
        "buildings": buildings,
        "equipment": items,
        "pipes": [],
        "structures": structures,
        "support_steel": [],
        "zones": [],
        "platforms": [],
        "inline": [],
        "step_overs": [],
        "supports": [],
        "penetrations": [],
        "unrouted": [],
        "routing": {},
    }
    document["support_steel"] = _declared_supports(document, layout.structures, structures_file)
    # zones with an explicit shape are obstacles of the router; derived ones need the routes
    explicit = None
    if layout.zones is not None:
        explicit = layout.zones.model_copy(
            update={"zones": [z for z in layout.zones.zones if z.shape is not None]}
        )
    document["zones"], _ = zone_entries(explicit, document)
    # declared platforms do not depend on the routes: the router sees them as walking levels
    # (vent risers keep their zones off them); proposals follow the routes below
    access = {p.tag: p.access for p in placements}
    document["platforms"] = [
        platform
        for item in items
        if access.get(item["tag"]) is not None
        for platform in platforms_for(item, access[item["tag"]], [], placement_name)
    ]
    network = sheets.network()
    if network:
        lists_lines = lists.get("lines")
        routed = route_model(
            document,
            network,
            lists_lines,
            layout.routing,
            layout.pipe_specs,
            plan,
            only=only,
            keep=(previous or {}).get("pipes") if only is not None else None,
            vent_radii=line_radii(layout.zones),
        )
        document["pipes"] = routed.pipes
        document["inline"] = routed.inline
        document["unrouted"] = routed.unrouted
        _piping_detail(document, lists_lines, plan)
        from chemeascode.domains.spatial.piping_detail import apply_operators

        apply_operators(document, layout.routing)
        stats.update(
            segments=routed.stats["segments"],
            routed=routed.stats["routed"],
            unrouted=routed.stats["unrouted"],
            route_seconds=routed.stats["seconds"],
        )
        document["routing"] = {
            "segments": routed.stats["segments"],
            "routed": routed.stats["routed"],
            "unrouted": routed.stats["unrouted"],
            "methods": routed.stats["methods"],
            "reasons": routed.stats.get("reasons", {}),
            "battery_limits": routed.stats.get("battery_limits", {}),
            "rack_fill": routed.stats.get("rack_fill", []),
        }
        used_sheets.update(sheets.files)
    zone_list, zone_findings = zone_entries(layout.zones, document)
    document["zones"] = zone_list
    findings += zone_findings
    platforms = []
    inline = document["inline"]
    for item in items:
        platforms += platforms_for(item, access.get(item["tag"]), inline, placement_name)
    for platform in platforms:
        refs = {"tag": platform["tag"]}
        platform["parts"] = _with_refs(platform["parts"], refs)
        platform["ladder"]["parts"] = _with_refs(platform["ladder"]["parts"], refs)
    document["platforms"] = platforms
    stats["platforms"] = len(platforms)
    from chemeascode.domains.spatial.penetrations import crossings

    document["penetrations"] = crossings(document)
    document["step_overs"] = step_overs(document)
    for step in document["step_overs"]:
        step["parts"] = _with_refs(step["parts"], {"lines": step["refs"]["lines"]})
    if document["site"] is None:
        del document["site"]
    cabling_sources = _cabling(workspace, document, sheets, layout, equipment)
    if cabling_sources is not None:
        used_sheets.update(sheets.files)
    _hvac(document, layout)
    _valve_platforms(document, plan)

    sources = [LAYOUT_FILES[kind] for kind in LAYOUT_FILES if workspace.layout_file(kind)]
    sources += [LIST_FILES[kind] for kind in INPUT_LISTS if workspace.list_file(kind)]
    sources += cabling_sources or []
    sources += [workspace.relative(path) for path in used_sheets]
    fingerprints = {path: file_fingerprint(workspace.root / path) for path in sorted(sources)}
    document["provenance"] = {
        "generator": GENERATOR,
        "generator_version": GENERATOR_VERSION,
        "generator_sha256": generator_fingerprint(),
        "sources": fingerprints,
        "output_sha256": "",
    }
    document = _validated(document)
    document["provenance"]["output_sha256"] = output_fingerprint(document)
    from chemeascode.domains.spatial.model_rules import model_rules

    findings += model_rules(document, layout.routing, plan)
    if cabling_sources is not None:
        from chemeascode.domains.spatial.trays import cable_entry_findings

        findings += cable_entry_findings(workspace, document)
    return Model(document, findings, stats)


def _cabling(
    workspace: Workspace, document: dict[str, Any], sheets: _Sheets, layout: Any, equipment: Any
) -> list[str] | None:
    """The cabling sections of *document* when the repository has a valid electrical list
    (:mod:`chemeascode.domains.spatial.trays`); the extra input files they were built from
    (None without an electrical list)."""
    if workspace.list_file("electrical") is None:
        return None
    parsed = workspace.parsed_lists(CABLING_LISTS)
    electrical = parsed.get("electrical")
    if electrical is None:
        return None  # validate reports the schema error
    from chemeascode.domains.control.electrical import motor_list
    from chemeascode.domains.equipment.datasheets import DATASHEET_DIR
    from chemeascode.domains.spatial.trays import build_cabling

    motors, _ = motor_list(workspace, equipment, electrical)
    files = {
        "electrical": LIST_FILES["electrical"],
        "trays": LAYOUT_FILES["trays"],
        "site_plan": LAYOUT_FILES["site_plan"],
    }
    sections = build_cabling(
        document,
        electrical,
        motors,
        sheets.instrument_functions(),
        parsed.get("instruments"),
        layout.trays,
        layout.site_plan,
        layout.routing.rules if layout.routing is not None else None,
        files,
    )
    for section in ("tray_tiers", "trays", "junction_boxes"):
        for entry in sections[section]:
            entry["parts"] = _with_refs(entry["parts"], dict(entry["refs"]))
    document.update(sections)
    found = [LIST_FILES[kind] for kind in CABLING_LISTS if workspace.list_file(kind)]
    for motor in motors:
        if motor.basis == "datasheet":
            found.append(f"{DATASHEET_DIR}/{motor.driven}.yaml")
    return found


def _valve_platforms(document: dict[str, Any], plan: Any) -> None:
    """Valve access platforms proposed for the valves out of reach, as structures of their
    own (``VP-<valve tag>``, ``source: generated``, ``review_needed``; :func:`structures.
    valve_platform_proposals`). Built last: nothing else is generated around them, and the
    rules leave them out until they are pinned."""
    from chemeascode.domains.spatial.criteria import criteria
    from chemeascode.domains.spatial.structures import frame_structure, valve_platform_proposals

    file = LAYOUT_FILES["structures"]
    for structure, reason, _ in valve_platform_proposals(document, criteria(plan), file):
        crit = criteria(plan)
        entry = frame_structure(structure, file, crit.escape_remote_fraction, crit.dead_end_m)
        refs = {"file": file}
        entry["parts"] = _with_refs(entry["parts"], refs)
        entry["walls"] = _with_refs(entry["walls"], refs)
        for way in [*entry["stairs"], *entry["ladders"]]:
            way["parts"] = _with_refs(way["parts"], refs)
            way["source"] = "generated"
        entry.update(source="generated", review_needed=True, reason=reason)
        document["structures"].append(entry)


def _hvac(document: dict[str, Any], layout: Any) -> None:
    """The HVAC sections of *document* when the repository has ``layout/hvac.yaml``
    (:mod:`chemeascode.domains.spatial.hvac`)."""
    if layout.hvac is None:
        return
    from chemeascode.domains.spatial.hvac import build_hvac

    sections = build_hvac(
        document,
        layout.hvac,
        layout.site_plan,
        layout.routing.rules if layout.routing is not None else None,
        LAYOUT_FILES["hvac"],
    )
    for unit in sections["hvac_units"]:
        unit["parts"] = _with_refs(unit["parts"], {"tag": unit["id"], "file": LAYOUT_FILES["hvac"]})
    for duct in sections["ducts"]:
        duct["parts"] = _with_refs(duct["parts"], {"tag": duct["unit"]})
    for room in sections["hvac_rooms"]:
        for terminal in room["terminals"]:
            terminal["parts"] = _with_refs(terminal["parts"], {"tag": room["id"]})
    document.update(sections)


def _validated(document: dict[str, Any]) -> dict[str, Any]:
    """*document* checked against :class:`~chemeascode.domains.spatial.schemas.LayoutModelFile`
    and dumped back (unset optional values left out), rounded to the millimetre."""
    from chemeascode.domains.spatial.schemas import LayoutModelFile

    model = LayoutModelFile.model_validate(_round(document))
    return _round(model.model_dump(mode="json", by_alias=True, exclude_none=True))


def write_model(workspace: Workspace, model: Model) -> tuple[Path, bool]:
    """Write *model* to :data:`~chemeascode.foundation.workspace.LAYOUT_MODEL_FILE`; the path
    and whether the file changed."""
    path = workspace.root / LAYOUT_MODEL_FILE
    text = model.text()
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return path, False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path, True



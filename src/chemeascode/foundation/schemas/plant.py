"""``plant.yaml``: what the plant is, which stage it is in, which sheets it has."""

from typing import Literal

from pydantic import Field, model_validator

from chemeascode.foundation.schema_base import Strict, optional_schema


class Stage(Strict):
    """An engineering stage. Checks name the stage they gate."""

    id: str
    title: str


class Generator(Strict):
    """The script a generated sheet is built by. A sheet with a generator is not edited by hand:
    change the script and run ``cheme regen``."""

    script: str = Field(
        description="Generator script from the repository root, e.g. scripts/draft_P-04.py. "
        "`cheme regen` copies the frame to a scratch file, runs `cheme run SCRIPT FILE` "
        "(the script edits FILE in place) and formats the result."
    )
    frame: str = Field(
        description="What the script starts from: a file in the repository (e.g. "
        "pid/frames/P-04.xml) or a git revision whose copy of the sheet file is the frame "
        "(e.g. 9aa9b38, the commit with the empty sheet). Quote a revision of digits only "
        "('8203912'): unquoted, YAML reads it as a number."
    )


class Sheet(Strict):
    """One P&ID sheet, a DEXPI 2.0.1 XML file.

    A ``planned`` sheet is part of the sheet split but not drawn yet: without its file it is
    reported as info (``cheme.sheet-planned``), and the listed items assigned to it
    (``sheet:``) are not reported missing from the P&IDs. Once the file exists it is validated
    like any other sheet. ``cheme sheet new`` writes the file and marks the sheet drafted.
    """

    id: str = Field(description="Sheet number as printed, e.g. P-01.")
    file: str = Field(
        default="",
        description="Path from the repository root, e.g. pid/P-01.xml (default pid/<id>.xml).",
    )
    title: str = ""
    kind: Literal["pid", "bfd", "pfd"] = Field(
        default="pid",
        description="pid: a P&ID; bfd/pfd: a block or process flow diagram generated from "
        "process/*.yaml by `cheme process build` (file default process/<id>.xml).",
    )
    generator: Generator | Literal["flowsheet"] | None = Field(
        default=None,
        description="Set for a generated sheet (rebuilt by `cheme regen`, no hand edits); "
        "leave out for a hand-maintained sheet. bfd/pfd sheets: flowsheet (the default).",
    )
    status: Literal["planned", "drafted"] = Field(
        default="drafted",
        description="planned: declared, not drawn yet (no file needed); drafted: the file exists.",
    )

    @model_validator(mode="after")
    def _default_file(self) -> "Sheet":
        if self.kind == "pid" and self.generator == "flowsheet":
            raise ValueError("generator: flowsheet is for kind bfd or pfd sheets")
        if self.kind != "pid":
            if isinstance(self.generator, Generator):
                raise ValueError(
                    f"a {self.kind} sheet is generated by `cheme process build` "
                    "(generator: flowsheet), not by a script"
                )
            self.generator = "flowsheet"
        if not self.file:
            self.file = f"pid/{self.id}.xml" if self.kind == "pid" else f"process/{self.id}.xml"
        return self


class Project(Strict):
    """The project the plant is engineered in: what ``cheme sheet new`` writes into the
    title block of each sheet (MetaData and the title-block texts)."""

    number: str = Field(default="", description="Project number, e.g. 24-017.")
    name: str = Field(default="", description="Project name (default: the plant name).")
    client: str = Field(default="", description="Client (EnterpriseName in the title block).")
    site: str = Field(default="", description="Site (SiteName in the title block).")
    revision: str = Field(default="A", description="Revision new sheets start at.")


class Issues(Strict):
    """Where the plant's issues are tracked: a GitHub repository and the label of this plant.

    The labels follow the engineering vocabulary of docs/framework/issues.md (type:, gate:,
    discipline:, source:, status:, waiting:)."""

    repository: str = Field(
        pattern=r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$",
        description="owner/name of the GitHub repository, e.g. ChemE-as-Code/process-library.",
    )
    label: str = Field(
        min_length=1, description="The label of this plant's issues, e.g. process:asu-1."
    )
    web: str = Field(
        default="https://github.com",
        pattern=r"^https://",
        description="Base URL of the issue pages, for links only. The issues are always read from "
        "api.github.com: a plant file cannot send the reader's token elsewhere.",
    )
    forms: dict[str, str] = Field(
        default_factory=dict,
        description="Issue form file per type (action, hold, tq, change), for new-issue links, "
        "e.g. {action: 1-action-item.yml}; without it, new issues open the template chooser.",
    )


class PlantConfig(Strict, optional_schema("plant")):
    """The root file of a plant repository."""

    name: str
    requires: str | None = Field(
        default=None,
        pattern=r"^cheme-as-code\s*>=\s*\d+(\.\d+){0,2}$",
        description="The oldest cheme-as-code this repository needs, e.g. cheme-as-code>=0.7. "
        "Every command of an older cheme-as-code stops with an upgrade hint before any schema "
        "error.",
    )
    description: str = ""
    units: str = Field(default="SI", description="Unit system of the YAML lists.")
    stage: str = Field(default="concept", description="Id of the current stage.")
    stages: list[Stage] = Field(
        default_factory=lambda: [
            Stage(id="concept", title="Concept and feasibility"),
            Stage(id="basic", title="Basic engineering"),
            Stage(id="detail", title="Detail engineering"),
        ]
    )
    project: Project | None = Field(
        default=None, description="Project data for the title blocks (`cheme sheet new`)."
    )
    sheets: list[Sheet] = Field(
        default_factory=list, description="P&ID sheets. Empty means every pid/*.xml."
    )
    issues: Issues | None = Field(
        default=None,
        description="Where the plant's issues are tracked (cheme issues, the issues gate kind, "
        "GET /api/issues); omitted: the plant tracks none.",
    )

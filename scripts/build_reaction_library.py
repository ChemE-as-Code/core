"""Build the reaction library (src/chemeascode/domains/process/data/library/) from its curated
source, scripts/reaction_library.yaml, with the components' data from chemicals (extra props):

    uv run python scripts/build_reaction_library.py [--check]

Every component gets its molar mass, critical constants and ideal-gas data. The heat capacity is
Poling's polynomial where the entry's window ends at 1000 K or below, else fitted to thermo's
ideal-gas heat capacity from 298.15 K to the window's top (rounded up to 100 K). A value
chemicals does not know is left out (the component then has no equilibrium or duty). --check
exits 1 when a generated file differs from what is committed.
"""

from __future__ import annotations

import contextlib
import math
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts" / "reaction_library.yaml"
TARGET = ROOT / "src" / "chemeascode" / "domains" / "process" / "data" / "library"
HEADER = """\
# GENERATED by scripts/build_reaction_library.py from scripts/reaction_library.yaml: edit that
# file and rebuild, never this one. Add the entry to a plant with `cheme chemistry library {id}
# --add`. Catalyst windows are typical industrial ranges (provenance assumed).
"""
CATALYST_SOURCE = "typical industrial range; confirm with the licensor's or vendor's data"
#: The note of each model basis whose entry does not write its own.
BASIS_NOTES = {
    "stoichiometry_only": "no conversion, selectivity, equilibrium basis or rate law: source and "
    "choose the reactor model separately",
    "equilibrium": "ideal-gas equilibrium limit from the components' formation data, without "
    "fugacity corrections or a rate law: how closely a reactor approaches it is not given",
}


def component(cid: str, record: dict, top: float) -> dict:
    """The component's data, its heat capacity valid up to *top* K (the highest window of the
    entries that use it): Poling's where its range reaches *top*, else fitted to thermo."""
    from chemeascode.domains.chemistry.eos import lookup_critical
    from chemeascode.domains.chemistry.thermochemistry import lookup_ideal_gas
    from chemeascode.integrations.thermo import ideal_gas_formation

    out = {"id": cid, "name": record["name"], "formula": record["formula"], "cas": record["cas"]}
    try:
        out["molar_mass"] = round(ideal_gas_formation(record["cas"])["molar_mass"], 4)
    except ValueError:
        from chemeascode.domains.chemistry.formulas import molar_mass

        out["molar_mass"] = round(molar_mass(record["formula"]), 4)
    with contextlib.suppress(ValueError):  # left out: chemicals knows no value
        out["critical"] = lookup_critical(record["cas"]).model_dump(mode="json")
    fit = None
    with contextlib.suppress(ValueError):
        poling = ideal_gas_formation(record["cas"])["temperature_range"]
        if poling is not None and poling[1] < top:
            fit = (298.15, math.ceil(top / 100.0) * 100.0)
    with contextlib.suppress(ValueError):
        ideal, _ = lookup_ideal_gas(record["cas"], fit)
        out["ideal_gas"] = ideal.model_dump(mode="json")
    return out


def build() -> dict[str, str]:
    source = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    known = source["components"]
    texts = {}
    # one record per component, valid over every entry that uses it (so entries agree)
    tops: dict[str, float] = {}
    for entry in source["entries"].values():
        for reaction in entry["reactions"]:
            for name in reaction["stoichiometry"]:
                tops[name] = max(tops.get(name, 0.0), entry["window"]["temperature"][1])
    records = {name: component(name, known[name], top) for name, top in tops.items()}
    for eid, entry in source["entries"].items():
        used: list[str] = []
        for reaction in entry["reactions"]:
            used += [n for n in reaction["stoichiometry"] if n not in used]
        catalysts = []
        for cat in entry.get("catalysts") or []:
            record = dict(cat)
            window = record.pop("window", None)
            if window:
                record["window"] = {**window, "provenance": "assumed", "source": CATALYST_SOURCE}
            record["sources"] = entry.get("sources", [])
            catalysts.append(record)
        basis = dict(entry["model_basis"])
        if not basis.get("note") and basis["kind"] in BASIS_NOTES:
            basis["note"] = BASIS_NOTES[basis["kind"]]
        document = {
            "schema": "cheme/library/v1",
            "kind": "library-entry",
            "id": eid,
            "title": entry["title"],
            "window": entry["window"],
            "components": [records[c] for c in used],
            "reactions": entry["reactions"],
            "model_basis": basis,
            "catalysts": catalysts,
            "sources": entry.get("sources", []),
        }
        body = yaml.safe_dump(document, sort_keys=False, width=100, allow_unicode=True)
        texts[f"{eid}.yaml"] = HEADER.replace("{id}", eid) + body
    return texts


def main() -> int:
    texts = build()
    if "--check" in sys.argv:
        stale = [
            name
            for name, text in texts.items()
            if not (TARGET / name).is_file() or (TARGET / name).read_text(encoding="utf-8") != text
        ]
        extra = sorted(p.name for p in TARGET.glob("*.yaml") if p.name not in texts)
        for name in stale + extra:
            print(f"{TARGET / name}: not current; run scripts/build_reaction_library.py")
        return 1 if stale or extra else 0
    TARGET.mkdir(parents=True, exist_ok=True)
    for name, text in texts.items():
        (TARGET / name).write_text(text, encoding="utf-8")
    for path in TARGET.glob("*.yaml"):
        if path.name not in texts:
            path.unlink()
    print(f"{TARGET}: {len(texts)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
